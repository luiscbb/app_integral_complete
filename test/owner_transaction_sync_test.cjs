// Requires @electric-sql/pglite to be available on NODE_PATH.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { test } = require('node:test');
const { PGlite } = require('@electric-sql/pglite');

test('owner transaction sync is atomic, retryable and business-bound', async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create role authenticated nologin;
      create role anon nologin;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
      $$;
      grant usage on schema public, auth to authenticated, anon;
      create table public.business_memberships (
        user_id uuid not null, billar_id text not null, role text not null,
        is_active boolean not null, must_change_password boolean not null
      );
      create table public.billar_settings (user_id uuid not null, billar_id text not null);
      create table public.providers (id bigint primary key, billar_id text not null);
      create table public.products (id bigint primary key, billar_id text not null);
      create table public.sales_history (
        id bigint generated by default as identity primary key,
        billar_id text not null, total double precision not null, paid double precision not null,
        date text not null, type text not null, source_module text, payment_method text not null,
        cancelled boolean not null default false, customer_key text
      );
      create table public.sale_details (
        id bigint generated by default as identity primary key,
        sale_id bigint not null references public.sales_history(id), product_id bigint,
        product_name text not null, quantity double precision not null,
        price_at_sale double precision not null, cost_at_sale numeric not null default 0,
        cancelled boolean not null default false
      );
      create table public.purchases (
        id bigint generated by default as identity primary key,
        billar_id text not null, provider_id bigint references public.providers(id),
        total double precision not null, date text not null, reference text, created_by text,
        cash_source text, cancelled boolean not null default false
      );
      create table public.purchase_details (
        id bigint generated by default as identity primary key,
        purchase_id bigint not null references public.purchases(id), product_id bigint not null,
        quantity double precision not null, cost_per_unit double precision not null,
        created_by text, cancelled boolean not null default false
      );
      insert into public.billar_settings values
        ('00000000-0000-0000-0000-000000000001', 'A'),
        ('00000000-0000-0000-0000-000000000002', 'B');
      insert into public.business_memberships values
        ('00000000-0000-0000-0000-000000000001', 'A', 'admin', true, false),
        ('00000000-0000-0000-0000-000000000002', 'B', 'admin', true, false),
        ('00000000-0000-0000-0000-000000000003', 'A', 'manager', true, false);
      insert into public.providers values (1, 'A'), (2, 'B');
      insert into public.products values (1, 'A'), (2, 'B');
    `);
    await db.exec(fs.readFileSync(
      path.join(__dirname, '..', 'supabase', 'purchase_payment_terms_partial.sql'),
      'utf8',
    ));
    const sql = fs.readFileSync(
      path.join(__dirname, '..', 'supabase', 'owner_transaction_sync_partial.sql'),
      'utf8',
    );
    await db.exec(sql);
    await db.exec(sql);
    const diagnosticSql = fs.readFileSync(
      path.join(__dirname, '..', 'supabase', 'owner_sync_schema_diagnostic.sql'),
      'utf8',
    );
    const diagnostic = (await db.query(diagnosticSql)).rows[0].diagnostic;
    assert.equal(diagnostic.tables.find(table => table.name === 'sales_history').rls_enabled, false);
    assert.ok(diagnostic.columns.some(column =>
      column.table_name === 'sales_history' && column.column_name === 'sync_client_id'));
    assert.ok(diagnostic.functions.some(fn =>
      fn.name === 'sync_owner_purchase_with_payment' && fn.installed));
    const isolationSql = fs.readFileSync(
      path.join(__dirname, '..', 'supabase', 'account_isolation_diagnostic.sql'),
      'utf8',
    );
    const isolation = (await db.query(isolationSql)).rows[0].diagnostic;
    assert.equal(isolation.transaction_ids.find(id => id.table_name === 'sales_history').is_identity, 'YES');
    assert.equal(isolation.tables.find(table => table.name === 'sales_history').has_billar_id, true);
    await db.exec('set role authenticated');
    const asUser = id => db.query(
      "select set_config('request.jwt.claim.sub', $1, false)",
      [`00000000-0000-0000-0000-${id.toString().padStart(12, '0')}`],
    );
    const requestId = '10000000-0000-4000-8000-000000000001';
    const sale = { total: 10, paid: 10, date: '2026-01-01', type: 'Mesa',
      payment_method: 'Efectivo', cancelled: false };
    const purchase = { total: 5, date: '2026-01-01', provider_id: 1,
      reference: '', created_by: 'ADMIN', cash_source: 'caja', cancelled: false };
    const saleDetail = [{ product_name: 'Producto', quantity: 1, price_at_sale: 10 }];
    const purchaseDetail = [{ product_id: 1, quantity: 1, cost_per_unit: 5 }];
    const call = (kind, business, cloudId, header, details, id = requestId) => db.query(
      `select public.sync_owner_${kind}${kind === 'purchase' && Object.hasOwn(header, 'payment_condition') ? '_with_payment' : ''}($1::uuid, $2, $3::bigint, $4::jsonb, $5::jsonb) as id`,
      [id, business, cloudId, JSON.stringify(header), JSON.stringify(details)],
    );
    await asUser(3);
    await assert.rejects(call('sale', 'A', null, sale, saleDetail), /administrador activo/i);
    await asUser(1);
    await assert.rejects(db.query('select * from public.owner_transaction_sync_requests'), /permission denied/i);
    await assert.rejects(
      call('sale', 'A', null, sale, [{ quantity: 1, price_at_sale: 10 }]),
      /null value/i,
    );
    const saleId = (await call('sale', 'A', null, sale, saleDetail)).rows[0].id;
    assert.equal((await call('sale', 'A', null, sale, saleDetail)).rows[0].id, saleId);
    await assert.rejects(
      call('sale', 'A', null, { ...sale, total: 99 }, saleDetail),
      /ya fue utilizado/i,
    );
    const purchaseRequest = '10000000-0000-4000-8000-000000000002';
    const purchaseId = (await call('purchase', 'A', null, purchase, purchaseDetail, purchaseRequest)).rows[0].id;
    assert.equal((await call('purchase', 'A', null, purchase, purchaseDetail, purchaseRequest)).rows[0].id, purchaseId);
    await assert.rejects(
      call('purchase', 'A', null, { ...purchase, provider_id: 2 }, purchaseDetail,
        '10000000-0000-4000-8000-000000000003'),
      /proveedor no pertenece/i,
    );
    await assert.rejects(
      call('sale', 'A', null, sale, [{ ...saleDetail[0], product_id: 2 }],
        '10000000-0000-4000-8000-000000000008'),
      /producto no está disponible/i,
    );
    await assert.rejects(
      call('sale', 'A', saleId, sale, [{ ...saleDetail[0], product_id: 999 }],
        '10000000-0000-4000-8000-000000000009'),
      /producto no está disponible/i,
    );
    for (const productId of [2, 999, null]) {
      await assert.rejects(
        call('purchase', 'A', purchaseId, purchase,
          [{ ...purchaseDetail[0], product_id: productId }],
          '10000000-0000-4000-8000-000000000010'),
        /producto no está disponible/i,
      );
    }
    await assert.rejects(
      call('sale', 'A', saleId, { ...sale, total: 99 }, [{ quantity: 1 }],
        '10000000-0000-4000-8000-000000000004'),
      /null value/i,
    );
    const cancellation = '10000000-0000-4000-8000-000000000007';
    await call('sale', 'A', saleId, { ...sale, cancelled: true }, saleDetail, cancellation);
    assert.equal((await call('sale', 'A', null, sale, saleDetail)).rows[0].id, saleId);
    await asUser(2);
    await assert.rejects(call('sale', 'B', null, sale, saleDetail), /ya fue utilizado/i);
    await assert.rejects(
      call('sale', 'B', saleId, sale, saleDetail, '10000000-0000-4000-8000-000000000005'),
      /no está disponible/i,
    );
    await assert.rejects(
      call('purchase', 'B', purchaseId, { ...purchase, provider_id: 2 }, purchaseDetail,
        '10000000-0000-4000-8000-000000000006'),
      /no está disponible/i,
    );
    await db.exec('reset role');
    assert.equal((await db.query('select count(*)::int as n from public.sales_history')).rows[0].n, 1);
    assert.equal((await db.query('select total from public.sales_history')).rows[0].total, 10);
    assert.equal((await db.query('select cancelled from public.sales_history')).rows[0].cancelled, true);
    assert.equal((await db.query('select count(*)::int as n from public.sale_details')).rows[0].n, 1);
    assert.equal((await db.query('select count(*)::int as n from public.purchases')).rows[0].n, 1);
    assert.deepEqual((await db.query(
      'select payment_condition, payment_method, credit_days, due_date, paid_amount, balance_due from public.purchases where id = $1',
      [purchaseId],
    )).rows[0], {
      payment_condition: null, payment_method: null, credit_days: null,
      due_date: null, paid_amount: null, balance_due: null,
    });
    assert.equal((await db.query('select count(*)::int as n from public.purchase_details')).rows[0].n, 1);
    assert.equal((await db.query('select count(*)::int as n from public.owner_transaction_sync_requests')).rows[0].n, 3);
    await db.exec('set role authenticated');
    await asUser(1);
    const uuid = n => `20000000-0000-4000-8000-${n.toString().padStart(12, '0')}`;
    const credit = {
      ...purchase, date: '2026-01-31T12:00:00Z', cash_source: null,
      payment_condition: 'credito', payment_method: null, credit_days: 30,
      due_date: '2026-03-02', paid_amount: 0, balance_due: 5,
    };
    await asUser(3);
    await assert.rejects(call('purchase', 'A', null, credit, purchaseDetail, uuid(1)), /administrador activo/i);
    await asUser(1);
    for (const change of [
      { cash_source: 'caja' }, { provider_id: null }, { credit_days: 1.5 },
      { paid_amount: 0.01, balance_due: 4.99 }, { due_date: '2026-03-01' },
      { total: 6, balance_due: 6 },
    ]) {
      await assert.rejects(call('purchase', 'A', null, { ...credit, ...change }, purchaseDetail, uuid(1)),
        /crédito|vencimiento|total|proveedor|pago/i);
    }
    const creditId = (await call('purchase', 'A', null, credit, purchaseDetail, uuid(1))).rows[0].id;
    assert.equal((await call('purchase', 'A', null, credit, purchaseDetail, uuid(1))).rows[0].id, creditId);
    await assert.rejects(
      call('purchase', 'A', null, { ...credit, credit_days: 0, due_date: '2026-01-31' }, purchaseDetail, uuid(1)),
      /identificador.*utilizado/i,
    );
    await assert.rejects(
      call('purchase', 'A', creditId, { ...credit, credit_days: 0, due_date: '2026-01-31' }, purchaseDetail, uuid(2)),
      /no se pueden cambiar/i,
    );
    await assert.rejects(call('purchase', 'A', creditId, purchase, purchaseDetail, uuid(2)), /actualiza el cliente/i);
    await assert.rejects(call('purchase', 'A', purchaseId, credit, purchaseDetail, uuid(2)), /histórica/i);
    await call('purchase', 'A', creditId, { ...credit, date: '2026-01-31T06:00:00-06:00', cancelled: true }, purchaseDetail, uuid(2));
    await db.exec('reset role');
    const storedCredit = (await db.query('select cancelled, cash_source, paid_amount, balance_due, due_date::text as due_date from public.purchases where id = $1', [creditId])).rows[0];
    assert.equal(storedCredit.cancelled, true);
    assert.equal(storedCredit.cash_source, null);
    assert.equal(storedCredit.balance_due, 5);
    assert.equal(storedCredit.paid_amount, 0);
    assert.equal(storedCredit.due_date, '2026-03-02');
    await db.exec('set role authenticated');
    for (const [n, method, source] of [
      [3, 'efectivo', 'caja'], [4, 'efectivo', 'cajero'],
      [5, 'tarjeta', 'tarjeta'], [6, 'transferencia', 'transferencia'],
    ]) {
      const paid = {
        ...purchase, cash_source: source, payment_condition: 'contado',
        payment_method: method, credit_days: null, due_date: null,
        paid_amount: 5, balance_due: 0,
      };
      const id = (await call('purchase', 'A', null, paid, purchaseDetail, uuid(n))).rows[0].id;
      await db.exec('reset role');
      const stored = (await db.query('select * from public.purchases where id = $1', [id])).rows[0];
      assert.equal(stored.payment_method, method);
      assert.equal(stored.paid_amount, 5);
      assert.equal(stored.balance_due, 0);
      await db.exec('set role authenticated');
    }
    await db.exec('reset role');
    const beforeReapply = (await db.query('select * from public.purchases order by id')).rows;
    await db.exec(sql);
    assert.deepEqual((await db.query('select * from public.purchases order by id')).rows, beforeReapply);
    await db.exec(`
      update public.business_memberships set is_active = false
      where user_id = '00000000-0000-0000-0000-000000000001';
      set role authenticated;
    `);
    await asUser(1);
    await assert.rejects(call('sale', 'A', null, sale, saleDetail), /administrador activo/i);
    await db.exec('reset role');
    await db.exec('set role anon');
    await assert.rejects(call('sale', 'A', null, sale, saleDetail), /permission denied/i);
    await assert.rejects(call('purchase', 'A', null, credit, purchaseDetail, uuid(7)), /permission denied/i);
  } finally {
    await db.close();
  }
});
