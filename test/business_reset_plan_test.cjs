// Requires @electric-sql/pglite to be available on NODE_PATH.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { test } = require('node:test');
const { PGlite } = require('@electric-sql/pglite');

const sql = fs.readFileSync(
  path.join(__dirname, '..', 'supabase', 'business_reset_plan.sql'), 'utf8',
);
const expected = {
  billiard_tables: 11,
  cash_outflow_concepts: 3,
  cash_outflows: 5,
  cashier_sessions: 0,
  categories: 2,
  inventory_movements: 52,
  match_results: 0,
  pending_sales: 0,
  products: 4,
  providers: 2,
  purchases: 4,
  sales_history: 34,
  billar_tournaments: 7,
  personal_clients: 1,
  personal_customer_accounts: 3,
  players: 3,
  owner_transaction_sync_requests: 0,
  provider_archive_requests: 0,
  product_stock_reconciliation_audit: 0,
};

async function fixture() {
  const db = new PGlite();
  await db.exec(`
    create schema auth;
    create schema storage;
    create table auth.users (id uuid primary key);
    insert into auth.users values
      ('00000000-0000-0000-0000-000000000001'),
      ('00000000-0000-0000-0000-000000000002'),
      ('00000000-0000-0000-0000-000000000003');
    create table storage.objects (name text);
    insert into storage.objects values ('logo'), ('avatar');
    create table billar_settings (billar_id text, user_id uuid);
    create table business_identity_registry (billar_id text, owner_user_id uuid);
    create table business_memberships (billar_id text, user_id uuid);
    insert into billar_settings values ('A', '00000000-0000-0000-0000-000000000001');
    insert into business_identity_registry select billar_id, user_id from billar_settings;
    insert into business_memberships select billar_id, user_id from billar_settings;
  `);
  for (const name of Object.keys(expected)) {
    await db.exec(`create table public.${name} (
      id bigint generated by default as identity primary key, billar_id text
    )`);
  }
  await db.exec(`
    alter table purchases add column provider_id bigint references providers(id);
    alter table inventory_movements add column product_id bigint references products(id) on delete restrict;
    alter table match_results add column player1_id bigint references players(id) on delete cascade;
    create table sale_details (
      sale_id bigint references sales_history(id) on delete cascade
    );
    create table purchase_details (
      purchase_id bigint references purchases(id) on delete cascade
    );
    create table promo_items (
      parent_id bigint references products(id) on delete cascade, child_id bigint
    );
    create table provider_products (
      provider_id bigint references providers(id) on delete cascade,
      product_id bigint references products(id) on delete cascade
    );
  `);
  for (const [name, count] of Object.entries(expected)) {
    await db.query(`insert into public.${name} (billar_id)
      select 'A' from generate_series(1, $1::integer)`, [count]);
  }
  await db.exec(`
    update purchases set provider_id = 1;
    update inventory_movements set product_id = 1;
    insert into sale_details select 1 from generate_series(1, 57);
    insert into purchase_details select 1 from generate_series(1, 4);
    insert into promo_items values (1, 2), (1, 3);
  `);
  return db;
}

test('reset removes only the approved operational data and preserves accounts and storage', async () => {
  const db = await fixture();
  try {
    await db.exec(sql);
    for (const name of Object.keys(expected)) {
      assert.equal(Number((await db.query(`select count(*) as n from public.${name}`)).rows[0].n), 0);
    }
    for (const name of ['sale_details', 'purchase_details', 'promo_items', 'provider_products']) {
      assert.equal(Number((await db.query(`select count(*) as n from public.${name}`)).rows[0].n), 0);
    }
    for (const [name, count] of [
      ['auth.users', 3], ['storage.objects', 2], ['public.billar_settings', 1],
      ['public.business_memberships', 1], ['public.business_identity_registry', 1],
    ]) {
      assert.equal(Number((await db.query(`select count(*) as n from ${name}`)).rows[0].n), count);
    }
  } finally {
    await db.close();
  }
});

test('reset aborts without deleting data when counts or business scope differ', async () => {
  for (const change of [
    "insert into products (billar_id) values ('A')",
    "insert into products (billar_id) values ('B')",
    'delete from sale_details where ctid in (select ctid from sale_details limit 1)',
    "update business_identity_registry set owner_user_id = '00000000-0000-0000-0000-000000000002'",
  ]) {
    const db = await fixture();
    try {
      await db.exec(change);
      await assert.rejects(db.exec(sql), /revisar el plan|identidad del billar/i);
      await db.exec('rollback');
      assert.equal(Number((await db.query('select count(*) as n from sales_history')).rows[0].n), 34);
      assert.equal(Number((await db.query('select count(*) as n from inventory_movements')).rows[0].n), 52);
      assert.equal(Number((await db.query('select count(*) as n from auth.users')).rows[0].n), 3);
    } finally {
      await db.close();
    }
  }
});
