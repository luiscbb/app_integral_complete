const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { test } = require('node:test');
const { PGlite } = require('@electric-sql/pglite');
const { buildStaffRollout, buildStaffPurchaseReportsUpdate, buildStaffReportsUpdate } = require('../supabase/build_staff_rollout.cjs');

test('grouped rollout rolls back failures and preserves owner access, data and private storage', async () => {
  const db = new PGlite();
  const ownerA = '00000000-0000-0000-0000-000000000001';
  const ownerB = '00000000-0000-0000-0000-000000000002';
  try {
    await db.exec(`
      create role authenticated nologin;
      create role anon nologin;
      create role service_role nologin;
      create schema auth;
      create schema storage;
      alter default privileges in schema public grant execute on functions to anon, authenticated, service_role;
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
      $$;
      create function auth.jwt() returns jsonb language sql stable as $$
        select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb
      $$;
      create function storage.foldername(name text) returns text[] language sql immutable as $$
        select string_to_array(regexp_replace(name, '/[^/]*$', ''), '/')
      $$;
      grant usage on schema public, auth, storage to authenticated, anon, service_role;
      create table auth.users (id uuid primary key, email text, raw_app_meta_data jsonb);
      create table storage.buckets (id text primary key, public boolean not null);
      insert into storage.buckets values ('player_avatars', false),
        ('product_images', false), ('promo_images', false), ('other', true);
      create table storage.objects (bucket_id text, name text);
      alter table storage.objects enable row level security;
      create policy fixture_storage_private on storage.objects for select to authenticated
        using ((storage.foldername(name))[1] = 'A' and auth.uid() = '${ownerA}'::uuid);
      grant select on storage.objects to authenticated, anon;
      insert into storage.objects values ('product_images', 'A/logo.png'), ('product_images', 'B/logo.png');
      create table public.business_memberships (
        user_id uuid, billar_id text, role text, is_active boolean default true,
        username text, full_name text not null default '', job_title text not null default '',
        allowed_modules text[] not null default '{}', must_change_password boolean default false,
        staff_revision bigint not null default 0, email text, created_by uuid,
        primary key (user_id, billar_id)
      );
      create function public.has_billar_role(b text, r text[]) returns boolean
      language sql stable security definer set search_path = public, pg_temp as $$
        select exists (select 1 from public.business_memberships m
          where m.user_id = auth.uid() and m.billar_id = b and m.is_active and m.role = any(r))
      $$;
      create table public.billar_settings (
        user_id uuid, billar_id text, allow_negative_stock_sales boolean not null default false
      );
      create table public.products (
        id bigint primary key, billar_id text not null, name text not null,
        barcode text, description text, cost double precision, price double precision not null,
        stock double precision not null, image_path text, is_promo integer default 0,
        parent_id bigint, pieces_per_unit integer default 1, category text, presentation text,
        is_active boolean default true, stock_revision bigint not null default 0
      );
      create table public.providers (
        id bigint primary key, billar_id text not null, name text, phone text, email text,
        address text, contact_name text, notes text, category text, visit_days text,
        is_active boolean not null default true
      );
      create table public.sales_history (
        id bigint generated by default as identity primary key, billar_id text not null,
        type text not null, source_module text, date text not null, payment_method text not null,
        total double precision not null, paid double precision not null,
        customer_key text, cancelled boolean default false
      );
      create table public.sale_details (
        id bigint generated by default as identity primary key, sale_id bigint references public.sales_history(id),
        product_id bigint, product_name text not null, quantity double precision not null,
        price_at_sale double precision not null, cost_at_sale double precision default 0, cancelled boolean default false
      );
      create table public.purchases (
        id bigint generated by default as identity primary key, billar_id text not null,
        provider_id bigint references public.providers(id), total double precision not null,
        date text not null, reference text, created_by text, cash_source text not null,
        cancelled boolean default false
      );
      create table public.purchase_details (
        id bigint generated by default as identity primary key, purchase_id bigint references public.purchases(id),
        product_id bigint, quantity double precision not null, cost_per_unit double precision not null,
        created_by text, cancelled boolean default false
      );
      create table public.promo_items (parent_id bigint, child_id bigint, quantity integer);
      create table public.provider_products (provider_id bigint, product_id bigint);
      create table public.players (id bigint, billar_id text, auth_user_id uuid);
      create table public.inventory_movements (
        id bigint generated by default as identity primary key, billar_id text, product_id bigint,
        movement_type text, quantity double precision, unit_cost double precision, unit_price double precision,
        reference_id bigint, reference_type text, notes text
      );
      insert into public.business_memberships (user_id, billar_id, role) values
        ('${ownerA}', 'A', 'admin'), ('${ownerB}', 'B', 'admin');
      insert into public.billar_settings (user_id, billar_id) values ('${ownerA}', 'A'), ('${ownerB}', 'B');
      insert into public.products (id, billar_id, name, cost, price, stock) values
        (1, 'A', 'Existing A', 5, 10, 4), (2, 'B', 'Existing B', 5, 10, 9);
      insert into public.providers (id, billar_id, name) values (1, 'A', 'Supplier A'), (2, 'B', 'Supplier B');
      insert into public.purchases (billar_id, provider_id, total, date, cash_source)
        values ('A', 1, 5, '2026-01-01', 'caja');
    `);
    for (const table of [
      'billiard_tables', 'cash_outflow_concepts', 'cash_outflows', 'cashier_sessions',
      'categories', 'match_results', 'pending_sales', 'billar_tournaments',
      'personal_clients', 'personal_customer_accounts',
    ]) {
      await db.exec(`create table public.${table} (id bigint, billar_id text)`);
    }
    const tables = (await db.query("select tablename from pg_tables where schemaname = 'public'")).rows;
    for (const { tablename } of tables) {
      await db.exec(`grant select, insert, update, delete on public.${tablename} to authenticated, anon;
        create policy fixture_existing_access on public.${tablename} for all to authenticated
        using (true) with check (true)`);
    }
    await db.exec(fs.readFileSync(path.join(__dirname, '..', 'supabase', 'owner_business_scope_partial.sql'), 'utf8'));
    await db.exec(fs.readFileSync(path.join(__dirname, '..', 'supabase', 'product_stock_conflict_guard_partial.sql'), 'utf8'));
    const snapshot = async () => (await db.query(`
      select (select jsonb_agg(to_jsonb(p) order by id) from public.products p) as products,
        (select jsonb_agg(to_jsonb(m) order by user_id) from public.business_memberships m) as memberships,
        (select jsonb_agg(to_jsonb(b) order by id) from storage.buckets b) as buckets,
        (select jsonb_agg(to_jsonb(p) order by policyname) from pg_policies p where schemaname = 'storage') as storage_policies
    `)).rows[0];
    const before = await snapshot();
    const sql = buildStaffRollout();
    assert.equal(fs.readFileSync(path.join(__dirname, '..', 'supabase', 'staff_rollout_install.sql'), 'utf8'), sql);
    const broken = sql.replace('\ncommit;\n', '\nselect 1 / 0;\ncommit;\n');
    assert.notEqual(broken, sql);
    await assert.rejects(db.exec(broken), /division by zero/i);
    await db.exec('rollback');
    assert.deepEqual(await snapshot(), before);
    assert.equal((await db.query("select to_regclass('public.staff_account_requests') as table_name")).rows[0].table_name, null);
    assert.equal((await db.query("select count(*)::int as n from pg_attribute where attrelid = 'public.providers'::regclass and attname = 'credit_days'")).rows[0].n, 0);

    await db.exec(sql);
    await db.exec(sql);
    const after = await snapshot();
    assert.deepEqual({ ...after, storage_policies: before.storage_policies }, before);
    for (const policy of before.storage_policies) {
      assert.deepEqual(after.storage_policies.find(p => p.policyname === policy.policyname), policy);
    }
    assert.ok(after.storage_policies.filter(p =>
      !before.storage_policies.some(existing => existing.policyname === p.policyname),
    ).every(p => p.permissive === 'RESTRICTIVE' && p.cmd !== 'SELECT'));
    const diagnostic = (await db.query(fs.readFileSync(
      path.join(__dirname, '..', 'supabase', 'staff_rollout_diagnostic.sql'), 'utf8',
    ))).rows[0].diagnostic;
    assert.ok(diagnostic.staff_tables.every(table => table.installed && table.rls_enabled));
    assert.ok(diagnostic.staff_functions.every(fn => fn.installed));
    assert.ok(diagnostic.staff_functions.every(fn => !fn.anon_execute));
    assert.ok(diagnostic.purchase_payment_columns.every(column => column.installed));
    assert.ok(diagnostic.staff_functions.filter(fn => ![
      'has_staff_module_access', 'has_staff_pos_module_access', 'can_access_inventory',
    ].includes(fn.name)).every(fn => !fn.anon_execute && !fn.authenticated_execute));
    assert.equal((await db.query('select payment_condition from public.purchases where id = 1')).rows[0].payment_condition, null);

    await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${ownerA}', false)`);
    assert.deepEqual((await db.query('select id from public.products order by id')).rows, [{ id: 1 }]);
    assert.deepEqual((await db.query('select id from public.providers order by id')).rows, [{ id: 1 }]);
    assert.deepEqual((await db.query('select id from public.purchases order by id')).rows, [{ id: 1 }]);
    assert.equal((await db.query('select name from storage.objects')).rows[0].name, 'A/logo.png');
    await db.exec(`update public.products set price = 11 where id = 1;
      update public.providers set preferred_payment_method = 'credito', credit_days = 7 where id = 1`);
    const payment = {
      provider_id: 1, total: 5, date: '2026-01-01', reference: '', created_by: 'ADMIN',
      cash_source: null, cancelled: false, payment_condition: 'credito', payment_method: null,
      credit_days: 7, due_date: '2026-01-08', paid_amount: 0, balance_due: 5,
    };
    const saveCredit = () => db.query(
      'select public.sync_owner_purchase_with_payment($1::uuid, $2, $3::bigint, $4::jsonb, $5::jsonb) as id',
      ['10000000-0000-4000-8000-000000000001', 'A', null, JSON.stringify(payment),
        JSON.stringify([{ product_id: 1, quantity: 1, cost_per_unit: 5 }])],
    );
    const creditId = (await saveCredit()).rows[0].id;
    assert.equal((await saveCredit()).rows[0].id, creditId);
    assert.deepEqual((await db.query('select balance_due, cash_source from public.purchases where id = $1', [creditId])).rows,
      [{ balance_due: 5, cash_source: null }]);
    await assert.rejects(db.exec("insert into public.providers (id, billar_id, name) values (3, 'B', 'Wrong')"), /row-level security/i);
    await db.exec('reset role; set role anon');
    assert.equal((await db.query('select * from public.products')).rows.length, 0);
    assert.equal((await db.query('select * from storage.objects')).rows.length, 0);
    await db.exec(`reset role;
      insert into public.business_memberships (user_id, billar_id, role, username, full_name, job_title, allowed_modules)
      values ('00000000-0000-0000-0000-000000000003', 'A', 'manager', 'pilot', 'Pilot', 'Caja',
        '{quick_sale,inventory,purchases}')`);
    await assert.rejects(db.exec(sql), /sin cuentas de personal/i);
    await db.exec(`rollback; set role authenticated;
      select set_config('request.jwt.claim.sub', '00000000-0000-0000-0000-000000000003', false)`);
    assert.deepEqual((await db.query('select id from public.products order by id')).rows, [{ id: 1 }]);
    await assert.rejects(db.query("select public.staff_sale_products('A')"), /permission denied/i);
    await assert.rejects(db.exec("insert into public.providers (id, billar_id) values (3, 'A')"), /row-level security/i);
    await db.exec(`reset role;
      grant execute on function public.has_staff_module_access(text, text) to anon;
      grant execute on function public.has_staff_pos_module_access(text, text) to anon;
      update public.business_memberships set allowed_modules = '{players}' where username = 'pilot'`);
    const activation = fs.readFileSync(path.join(__dirname, '..', 'supabase', 'staff_pilot_activation.sql'), 'utf8');
    await assert.rejects(db.exec(activation), /fuera del piloto/i);
    await db.exec(`rollback;
      update public.business_memberships set allowed_modules = '{quick_sale,inventory,purchases}' where username = 'pilot'`);
    await db.exec(activation);
    await db.exec(activation);
    await db.exec(`update public.business_memberships
      set allowed_modules = '{billiard_tables,billiard_tables_open,billiard_tables_consume,dine_in,dine_in_open,dine_in_consume}'
      where username = 'pilot'`);
    await db.exec(activation);
    await db.exec(`update public.business_memberships
      set allowed_modules = '{billiard_tables}' where username = 'pilot'`);
    await assert.rejects(db.exec(activation), /fuera del piloto/i);
    await db.exec(`rollback;
      update public.business_memberships set allowed_modules = '{quick_sale,inventory,purchases}' where username = 'pilot'`);
    const permissions = (await db.query(fs.readFileSync(
      path.join(__dirname, '..', 'supabase', 'staff_rollout_diagnostic.sql'), 'utf8',
    ))).rows[0].diagnostic.staff_functions;
    assert.ok(permissions.every(fn => !fn.anon_execute));
    const serviceOnly = new Set([
      'reserve_staff_account', 'find_staff_creation_auth_user', 'finalize_staff_account',
      'stop_staff_password_recovery', 'complete_staff_password_change', 'update_staff_account',
    ]);
    assert.ok(permissions.filter(fn => serviceOnly.has(fn.name)).every(fn =>
      !fn.authenticated_execute && fn.service_role_execute));
    assert.ok(permissions.filter(fn => !serviceOnly.has(fn.name)).every(fn => fn.authenticated_execute));
    const beforeUpdate = (await db.query('select * from public.business_memberships order by user_id')).rows;
    await db.exec(buildStaffPurchaseReportsUpdate());
    await db.exec(buildStaffPurchaseReportsUpdate());
    assert.equal(fs.readFileSync(path.join(__dirname,'..','supabase','staff_reports_update.sql'),'utf8'),
      buildStaffReportsUpdate());
    await db.exec(buildStaffReportsUpdate());
    await db.exec(buildStaffReportsUpdate());
    assert.deepEqual((await db.query('select * from public.business_memberships order by user_id')).rows, beforeUpdate);
    await db.exec(`update public.business_memberships
      set allowed_modules = '{billiard_tables,billiard_tables_open,billiard_tables_consume}'
      where username = 'pilot'`);
    await assert.rejects(db.exec(`update public.business_memberships
      set allowed_modules = '{billiard_tables}' where username = 'pilot'`), /check constraint/i);
    await db.exec(`update public.business_memberships
      set allowed_modules = '{quick_sale,inventory,purchases}' where username = 'pilot'`);
    assert.deepEqual((await db.query(fs.readFileSync(
      path.join(__dirname, '..', 'supabase', 'staff_purchase_reports_diagnostic.sql'), 'utf8',
    ))).rows[0].diagnostic, {
      report_installed: true, report_authenticated_execute: true, report_anon_execute: false,
      report_security_definer: true, membership_constraint_supports_report: true,
      report_only_added_to_direct_purchase_policies: false, account_mutations_service_only: true,
    });
    await db.exec("update public.business_memberships set allowed_modules = '{reports_purchases}' where username = 'pilot'");
    await db.exec(`set role authenticated;
      select set_config('request.jwt.claim.sub', '00000000-0000-0000-0000-000000000003', false)`);
    const report = (await db.query(
      "select public.staff_purchase_report('A', '2026-01-01', '2026-02-01') as report",
    )).rows[0].report;
    assert.equal(report.count, 2);
    assert.equal(report.total, 10);
    assert.equal(report.balance, 5);
    assert.deepEqual((await db.query('select id from public.purchases')).rows, []);
    assert.deepEqual((await db.query('select id from public.providers')).rows, []);
    assert.deepEqual((await db.query('select id from public.purchase_details')).rows, []);
    await assert.rejects(db.exec("insert into public.providers (id, billar_id) values (3, 'A')"), /row-level security/i);
    await db.exec(`reset role;
      update public.business_memberships set allowed_modules = '{quick_sale,inventory,purchases}' where username = 'pilot'`);
    await db.exec(`set role authenticated;
      select set_config('request.jwt.claim.sub', '00000000-0000-0000-0000-000000000003', false)`);
    const catalog = (await db.query("select * from public.staff_sale_products('A')")).rows;
    assert.deepEqual(catalog.map(product => product.id), [1]);
    assert.equal(Object.hasOwn(catalog[0], 'cost'), false);
    await assert.rejects(db.query("select * from public.staff_sale_products('B')"), /permiso/i);
    await assert.rejects(db.query("select public.list_staff_accounts('A')"), /administrador/i);
    await assert.rejects(db.exec("insert into public.providers (id, billar_id) values (3, 'A')"), /row-level security/i);
    await db.exec('reset role; set role anon');
    await assert.rejects(db.query("select public.has_staff_module_access('A', 'purchases')"), /permission denied/i);
  } finally {
    await db.close();
  }
});
