// Requires @electric-sql/pglite to be available on NODE_PATH.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { test } = require('node:test');
const { PGlite } = require('@electric-sql/pglite');

test('staff sale recording is atomic, attributed and idempotent', async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create role authenticated nologin;
      create role anon nologin;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
      $$;
      grant usage on schema public, auth to authenticated;
      create table public.business_memberships (
        user_id uuid not null, billar_id text not null, role text not null,
        is_active boolean not null, username text, allowed_modules text[] not null,
        must_change_password boolean not null default false
      );
      create function public.has_billar_role(b text, r text[]) returns boolean
      language sql stable security definer set search_path = public, pg_temp as $$
        select exists (select 1 from public.business_memberships m
          where m.user_id = auth.uid() and m.billar_id = b and m.is_active
            and m.role = any(r))
      $$;
      create table public.products (
        id bigint primary key, billar_id text not null, name text not null,
        cost double precision, price double precision not null, stock double precision not null,
        is_promo integer not null default 0, parent_id bigint,
        pieces_per_unit integer not null default 1, is_active boolean not null default true
      );
      create table public.billar_settings (
        billar_id text not null, allow_negative_stock_sales boolean not null default false
      );
      create table public.promo_items (parent_id bigint not null, child_id bigint not null, quantity integer not null);
      create table public.inventory_movements (
        id bigint generated by default as identity primary key,
        billar_id text not null, product_id bigint not null, movement_type text not null,
        quantity double precision not null, unit_cost double precision not null,
        unit_price double precision not null, reference_id bigint,
        reference_type text, notes text
      );
      create table public.sales_history (
        id bigint generated by default as identity primary key,
        billar_id text not null, type text not null, source_module text,
        date text not null, payment_method text not null, total double precision not null,
        paid double precision not null, customer_key text, cancelled boolean not null default false
      );
      create table public.sale_details (
        id bigint generated by default as identity primary key,
        sale_id bigint not null references public.sales_history(id),
        product_id bigint, product_name text not null, quantity double precision not null,
        price_at_sale double precision not null, cost_at_sale double precision not null,
        cancelled boolean not null default false
      );
      insert into public.business_memberships values
        ('00000000-0000-0000-0000-000000000001', 'A', 'admin', true, null, '{}', false),
        ('00000000-0000-0000-0000-000000000002', 'A', 'manager', true, 'caja', '{quick_sale}', false),
        ('00000000-0000-0000-0000-000000000003', 'A', 'manager', true, 'otro', '{quick_sale}', false),
        ('00000000-0000-0000-0000-000000000004', 'A', 'manager', false, 'inactivo', '{quick_sale}', false),
        ('00000000-0000-0000-0000-000000000005', 'A', 'manager', true, 'nuevo', '{quick_sale}', true),
        ('00000000-0000-0000-0000-000000000006', 'A', 'manager', true, 'informes', '{reports}', false),
        ('00000000-0000-0000-0000-000000000007', 'B', 'admin', true, null, '{}', false);
      insert into public.products values
        (1, 'A', 'Producto', 3.5, 10, 10, 0, null, 1, true),
        (2, 'B', 'Otro', 7, 10, 10, 0, null, 1, true),
        (3, 'A', 'Caja', 14, 40, 0, 0, 1, 4, true),
        (4, 'A', 'Promo', 7, 15, 0, 1, null, 1, true),
        (5, 'A', 'Agotado', 2, 4, 0, 0, null, 1, true),
        (6, 'A', 'Promo incompleta', 5.5, 14, 0, 1, null, 1, true);
      insert into public.billar_settings values ('A', false), ('B', false);
      insert into public.promo_items values (4, 1, 2), (6, 1, 1), (6, 5, 1);
      alter table public.sales_history enable row level security;
      alter table public.sale_details enable row level security;
      grant select, insert, update, delete on public.sales_history, public.sale_details to authenticated;
    `);
    for (const file of [
      'product_stock_conflict_guard_partial.sql',
      'staff_inventory_guards_partial.sql',
      'staff_sales_guards_partial.sql',
      'staff_sale_recording_partial.sql',
    ]) {
      const sql = fs.readFileSync(path.join(__dirname, '..', 'supabase', file), 'utf8');
      await db.exec(sql);
      await db.exec(sql);
    }
    await db.exec('set role authenticated');

    const asUser = async (id) => db.query(
      "select set_config('request.jwt.claim.sub', $1, false)",
      [`00000000-0000-0000-0000-${id.toString().padStart(12, '0')}`],
    );
    const request = async (id, items, module = 'quick_sale', billar = 'A', total = 10) =>
      db.query(
        `select public.record_staff_sale($1::uuid, $2, $3, $4, $5, $6, $7, $8, $9, $10::jsonb) as id`,
        [id, billar, module, 'Venta Rápida', '2026-01-01', 'Efectivo', total, 10, null, JSON.stringify(items)],
      );
    const item = { product_id: 1, product_name: 'Producto', quantity: 1, price_at_sale: 10, cost_at_sale: 999 };
    const firstId = '10000000-0000-0000-0000-000000000001';
    const secondId = '10000000-0000-0000-0000-000000000002';

    await asUser(2);
    await assert.rejects(request(firstId, [item]), /permission denied/i);
    await assert.rejects(
      db.query('select public.get_staff_sale_reconciliation($1::uuid, $2)', [firstId, 'A']),
      /permission denied/i,
    );
    await db.exec(`
      reset role;
      grant execute on function public.record_staff_sale(
        uuid, text, text, text, text, text, double precision, double precision, text, jsonb
      ) to authenticated;
      grant execute on function public.get_staff_sale_reconciliation(uuid, text) to authenticated;
      set role authenticated;
    `);
    const first = (await request(firstId, [item])).rows[0].id;
    assert.equal((await request(firstId, [item])).rows[0].id, first);
    const receipt = (await db.query(
      'select public.get_staff_sale_reconciliation($1::uuid, $2) as receipt', [firstId, 'A'],
    )).rows[0].receipt;
    assert.equal(Number(receipt.sale_id), Number(first));
    assert.equal(receipt.request_id, firstId);
    assert.equal(receipt.stock.length, 1);
    assert.equal(Number(receipt.stock[0].product_id), 1);
    assert.equal(receipt.stock[0].stock, 9);
    assert.equal(Number(receipt.stock[0].stock_revision), 1);
    assert.equal(receipt.items.length, 1);
    assert.equal('cost_at_sale' in receipt.items[0], false);
    await db.exec(`
      reset role;
      update public.business_memberships set allowed_modules = '{quick_sale,reports}'
      where username = 'caja';
      set role authenticated;
    `);
    const receiptWithCost = (await db.query(
      'select public.get_staff_sale_reconciliation($1::uuid, $2) as receipt', [firstId, 'A'],
    )).rows[0].receipt;
    assert.equal(receiptWithCost.items[0].cost_at_sale, 3.5);
    await db.exec(`
      reset role;
      update public.business_memberships set allowed_modules = '{quick_sale}'
      where username = 'caja';
      set role authenticated;
    `);
    assert.deepEqual((await db.query('select product_id, cost_at_sale from public.sale_details')).rows, []);
    await db.exec('reset role');
    const details = (await db.query('select product_id, cost_at_sale from public.sale_details')).rows;
    assert.equal(details.length, 1);
    assert.equal(Number(details[0].product_id), 1);
    assert.equal(details[0].cost_at_sale, 3.5);
    await db.exec('set role authenticated');
    assert.deepEqual((await db.query('select id from public.staff_sale_audit')).rows, []);
    await assert.rejects(request(firstId, [{ ...item, quantity: 2 }]), /ya fue utilizado/i);
    await assert.rejects(
      request(secondId, [item, { ...item, product_id: 2 }]),
      /no pertenece/i,
    );
    assert.equal((await db.query('select id from public.sales_history')).rows.length, 1);
    await request(secondId, [item]);
    assert.equal((await db.query('select id from public.sales_history')).rows.length, 2);
    await assert.rejects(
      request('10000000-0000-0000-0000-000000000003', [{ ...item, quantity: 0 }]),
      /cantidad o precio inválido/i,
    );
    await assert.rejects(
      request('10000000-0000-0000-0000-000000000003', []),
      /al menos un detalle/i,
    );
    await assert.rejects(
      request('10000000-0000-0000-0000-000000000003', [item], 'quick_sale', 'A', 1),
      /total no coincide/i,
    );
    await assert.rejects(
      request('10000000-0000-0000-0000-000000000003', [{ ...item, price_at_sale: 1 }], 'quick_sale', 'A', 1),
      /precio del producto cambió/i,
    );
    assert.equal((await db.query('select id from public.sales_history')).rows.length, 2);
    await assert.rejects(request('10000000-0000-0000-0000-000000000003', [item], 'personal_account'), /no está habilitado/i);
    await assert.rejects(request('10000000-0000-0000-0000-000000000003', [item], 'quick_sale', 'B'), /permiso/i);
    await assert.rejects(request('10000000-0000-0000-0000-000000000003', [item], 'quick_sale', 'A', -1), /inválidos/i);
    await assert.rejects(db.query('select * from public.staff_sale_requests'), /permission denied/i);
    await assert.rejects(db.query("insert into public.staff_sale_audit (billar_id, actor_id, sale_id) values ('A', auth.uid(), 1)"), /permission denied/i);

    await db.exec('reset role');
    assert.equal((await db.query('select stock from public.products where id = 1')).rows[0].stock, 8);
    assert.equal((await db.query('select id from public.inventory_movements')).rows.length, 2);
    await db.exec('set role authenticated');
    await assert.rejects(
      request(
        '10000000-0000-0000-0000-000000000003',
        [{ product_id: 6, product_name: 'Promo incompleta', quantity: 1, price_at_sale: 14 }],
        'quick_sale', 'A', 14,
      ),
      /existencias suficientes/i,
    );
    await db.exec('reset role');
    assert.equal((await db.query('select stock from public.products where id = 1')).rows[0].stock, 8);
    assert.equal((await db.query('select id from public.inventory_movements')).rows.length, 2);
    await db.exec('set role authenticated');
    await request(
      '10000000-0000-0000-0000-000000000003',
      [{ product_id: 3, product_name: 'Caja', quantity: 1, price_at_sale: 40 }],
      'quick_sale', 'A', 40,
    );
    const promo = { product_id: 4, product_name: 'Promo', quantity: 1, price_at_sale: 15 };
    await request('10000000-0000-0000-0000-000000000004', [promo], 'quick_sale', 'A', 15);
    const promoReceipt = (await db.query(
      'select public.get_staff_sale_reconciliation($1::uuid, $2) as receipt',
      ['10000000-0000-0000-0000-000000000004', 'A'],
    )).rows[0].receipt;
    assert.equal(Number(promoReceipt.stock[0].product_id), 1);
    assert.equal(promoReceipt.stock[0].stock, 2);
    await assert.rejects(
      request('10000000-0000-0000-0000-000000000005', [{ ...promo, quantity: 2 }], 'quick_sale', 'A', 30),
      /existencias suficientes/i,
    );
    await db.exec('reset role');
    assert.equal((await db.query('select stock from public.products where id = 1')).rows[0].stock, 2);
    await db.query("update public.billar_settings set allow_negative_stock_sales = true where billar_id = 'A'");
    await db.exec('set role authenticated');
    await request('10000000-0000-0000-0000-000000000005', [{ ...promo, quantity: 2 }], 'quick_sale', 'A', 30);
    await db.exec('reset role');
    assert.equal((await db.query('select stock from public.products where id = 1')).rows[0].stock, -2);
    assert.equal((await db.query('select id from public.inventory_movements')).rows.length, 5);
    await db.exec('set role authenticated');
    const multiId = '10000000-0000-0000-0000-000000000006';
    await request(
      multiId,
      [{ product_id: 6, product_name: 'Promo incompleta', quantity: 1, price_at_sale: 14 }],
      'quick_sale', 'A', 14,
    );
    const multiReceipt = (await db.query(
      'select public.get_staff_sale_reconciliation($1::uuid, $2) as receipt',
      [multiId, 'A'],
    )).rows[0].receipt;
    assert.deepEqual(multiReceipt.stock.map((entry) => Number(entry.product_id)), [1, 5]);
    assert.deepEqual(multiReceipt.stock.map((entry) => entry.stock), [-3, -1]);

    await asUser(3);
    await assert.rejects(request(firstId, [item]), /ya fue utilizado/i);
    await assert.rejects(
      db.query('select public.get_staff_sale_reconciliation($1::uuid, $2)', [firstId, 'A']),
      /no se encontró/i,
    );
    for (const id of [4, 5, 6]) {
      await asUser(id);
      await assert.rejects(request('10000000-0000-0000-0000-000000000003', [item]), /permiso/i);
    }
    await asUser(7);
    assert.deepEqual((await db.query('select id from public.staff_sale_audit')).rows, []);
    await asUser(1);
    const audit = (await db.query('select actor_id, sale_id from public.staff_sale_audit order by id')).rows;
    assert.equal(audit.length, 6);
    assert.equal(audit[0].actor_id, '00000000-0000-0000-0000-000000000002');
    assert.equal(audit[0].sale_id, first);
  } finally {
    await db.close();
  }
});
