const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { test } = require('node:test');
const { PGlite } = require('@electric-sql/pglite');

test('table checkout is atomic, scoped and idempotent', async () => {
  const db = new PGlite();
  const actor = n => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
  const service = n => `10000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
  const request = n => `20000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
  try {
    await db.exec(`
      create role authenticated nologin;
      create role anon nologin;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
      $$;
      grant usage on schema public, auth to authenticated, anon;
      create table public.business_memberships (
        user_id uuid not null, billar_id text not null, role text not null,
        is_active boolean not null, must_change_password boolean not null,
        username text, allowed_modules text[] not null,
        primary key (user_id,billar_id)
      );
      create table public.billiard_tables (
        id bigint not null, billar_id text not null, name text not null,
        table_type text not null, is_occupied integer not null default 0,
        start_time timestamptz, orders text default '[]', is_deleted integer not null default 0,
        primary key (billar_id,id)
      );
      create table public.billar_settings (
        billar_id text not null, hourly_rate double precision not null,
        allow_negative_stock_sales boolean not null
      );
      create table public.products (
        id bigint primary key, billar_id text not null, name text not null,
        cost double precision, price double precision not null, stock double precision not null,
        is_promo integer not null default 0, parent_id bigint,
        pieces_per_unit integer not null default 1, is_active boolean not null default true
      );
      create table public.promo_items (parent_id bigint not null, child_id bigint not null, quantity integer not null);
      create table public.sales_history (
        id bigint generated by default as identity primary key,
        billar_id text not null, type text not null, source_module text,
        date text not null, payment_method text not null, total double precision not null,
        paid double precision not null, customer_key text, cancelled boolean not null default false
      );
      create table public.sale_details (
        id bigint generated by default as identity primary key, sale_id bigint not null,
        product_id bigint, product_name text not null, quantity double precision not null,
        price_at_sale double precision not null, cost_at_sale double precision not null,
        cancelled boolean not null default false
      );
      create table public.inventory_movements (
        id bigint generated by default as identity primary key,
        billar_id text not null, product_id bigint not null, movement_type text not null,
        quantity double precision not null, unit_cost double precision not null,
        unit_price double precision not null, reference_id bigint, reference_type text, notes text
      );
      insert into public.business_memberships values
        ('${actor(1)}','A','manager',true,false,'mesero','{billiard_tables,billiard_tables_open,billiard_tables_consume,dine_in,dine_in_open,dine_in_consume}'),
        ('${actor(2)}','A','manager',true,false,'cajero','{billiard_tables,billiard_tables_charge,billiard_tables_view_all,dine_in,dine_in_charge,dine_in_view_all}'),
        ('${actor(3)}','A','manager',true,false,'otro','{billiard_tables,billiard_tables_charge,billiard_tables_view_all}'),
        ('${actor(4)}','B','admin',true,false,null,'{}'),
        ('${actor(5)}','A','admin',true,false,null,'{}');
      insert into public.billar_settings values ('A',0,false),('B',0,false);
      insert into public.billiard_tables (id,billar_id,name,table_type) values
        (1,'A','Mesa 1','Billar'),(2,'A','Mesa 2','Billar'),
        (3,'A','Mesa 3','Billar'),(4,'A','Comanda 4','Comanda'),
        (5,'A','Pool 5','Pool');
      insert into public.products values
        (1,'A','Agua',3,10,20,0,null,1,true),
        (2,'A','Caja',12,40,0,0,1,4,true),
        (3,'A','Promo',7,15,0,1,null,1,true),
        (4,'A','Agotado',2,5,0,0,null,1,true),
        (5,'B','Ajeno',2,5,10,0,null,1,true);
      insert into public.promo_items values (3,1,2);
    `);
    for (const file of [
      'product_stock_conflict_guard_partial.sql',
      'staff_table_service_partial.sql',
      'staff_table_checkout_partial.sql',
      'staff_table_conflict_review_partial.sql',
      'staff_table_late_adjustment_partial.sql',
    ]) {
      const sql = fs.readFileSync(path.join(__dirname, '..', 'supabase', file), 'utf8');
      await db.exec(sql);
      await db.exec(sql);
    }
    const as = n => db.query("select set_config('request.jwt.claim.sub',$1,false)", [actor(n)]);
    const open = async (n, table, type = 'Billar') =>
      (await db.query('select public.staff_table_open($1,$2,$3,$4,now()) as data',
        [service(n), 'A', table, type])).rows[0].data;
    const add = async (n, s, product, quantity, price, type = 'Billar') =>
      (await db.query("select public.staff_table_add_consumption($1,'A',$2,$3,$4,$5,$6,$7,now()) as data",
        [request(n), service(s), type, product, `Producto ${product}`, quantity, price])).rows[0].data;
    const snapshot = async (s, type = 'Billar') =>
      (await db.query("select public.staff_table_checkout_snapshot('A',$1,$2,null,null) as data",
        [type, service(s)])).rows[0].data;
    const checkout = async (n, s, rev, total, paid = total, type = 'Billar', time = 0, business = 'A') =>
      (await db.query('select public.staff_table_checkout($1,$2,$3,$4,$5,$6,$7,$8,$9) as data',
        [request(n), business, type, service(s), rev, time, total, 'Efectivo', paid])).rows[0].data;
    const lateSnapshot = async (s, type = 'Billar') =>
      (await db.query("select public.staff_table_late_adjustment_snapshot('A',$1,$2,null) as data",
        [type, service(s)])).rows[0].data;
    const adjustLate = async (n, s, revision, total, paid = total, type = 'Billar', business = 'A') =>
      (await db.query('select public.staff_table_adjust_late_consumptions($1,$2,$3,$4,$5,$6,$7,$8) as data',
        [request(n), business, type, service(s), revision, total, 'Efectivo', paid])).rows[0].data;
    await db.exec('set role authenticated');
    await as(1);
    await assert.rejects(checkout(100, 1, 0, 0), /permission denied/i);
    await db.exec(`reset role;
      grant execute on function public.staff_table_checkout(uuid,text,text,uuid,bigint,double precision,double precision,text,double precision) to authenticated;
      set role authenticated`);
    await open(1, 1);
    await add(1, 1, 1, 1, 10);
    await add(2, 1, 2, 1, 40);
    await add(3, 1, 3, 1, 15);
    await assert.rejects(checkout(100, 1, 0, 65), /Sin permiso/i);
    await as(2);
    const current = await snapshot(1);
    await assert.rejects(checkout(100, 1, current.revision - 1, 65), e => e.code === 'PST02');
    await assert.rejects(checkout(100, 1, current.revision, 65, 65, 'Billar', 1), e => e.code === 'PST03');
    await assert.rejects(checkout(100, 1, current.revision, 64), /total no coincide/i);
    await assert.rejects(checkout(100, 1, current.revision, 65, 64), /debe cubrir el total/i);
    await assert.rejects(checkout(100, 1, current.revision, 65, 65, 'Billar', 0, 'B'), /Sin permiso/i);
    await db.exec('reset role');
    assert.equal((await db.query('select count(*)::int as n from public.sales_history')).rows[0].n, 0);
    assert.equal((await db.query('select stock from public.products where id=1')).rows[0].stock, 20);
    assert.equal((await db.query('select is_occupied from public.billiard_tables where id=1')).rows[0].is_occupied, 1);
    await db.exec('set role authenticated');
    const result = await checkout(100, 1, current.revision, 65, 70);
    assert.equal(result.total, 65);
    assert.equal(result.items.length, 3);
    assert.deepEqual(await checkout(100, 1, current.revision, 65, 70), result);
    await assert.rejects(checkout(100, 1, current.revision, 65, 71), /identificador/i);
    await assert.rejects(checkout(101, 1, current.revision, 65), /servicio activo/i);
    await as(3);
    await assert.rejects(checkout(100, 1, current.revision, 65, 70), /identificador/i);
    await as(1);
    assert.equal((await add(10, 1, 1, 1, 10)).late, true);
    await db.exec('reset role');
    assert.equal((await db.query('select stock from public.products where id=1')).rows[0].stock, 13);
    assert.equal((await db.query('select count(*)::int as n from public.sales_history')).rows[0].n, 1);
    assert.equal((await db.query('select count(*)::int as n from public.sale_details')).rows[0].n, 3);
    assert.equal((await db.query('select count(*)::int as n from public.inventory_movements')).rows[0].n, 3);
    assert.equal((await db.query('select is_occupied from public.billiard_tables where id=1')).rows[0].is_occupied, 0);
    await db.query('update public.sales_history set cancelled=true where id=$1', [result.sale_id]);
    await db.exec('set role authenticated');
    await as(2);
    await assert.rejects(checkout(100, 1, current.revision, 65, 70), /anulada/i);
    await db.exec('reset role');
    await db.query('update public.sales_history set cancelled=false where id=$1', [result.sale_id]);

    await db.exec('set role authenticated');
    await as(1);
    await open(2, 2);
    await add(11, 2, 1, 1, 10);
    await add(12, 2, 4, 1, 5);
    await as(2);
    const unavailable = await snapshot(2);
    await assert.rejects(checkout(102, 2, unavailable.revision, 15), /existencias suficientes/i);
    await db.exec('reset role');
    assert.equal((await db.query('select stock from public.products where id=1')).rows[0].stock, 13);
    assert.equal((await db.query('select count(*)::int as n from public.sales_history')).rows[0].n, 1);
    assert.equal((await db.query('select is_occupied from public.billiard_tables where id=2')).rows[0].is_occupied, 1);
    await db.exec(`
      update public.products set price=11 where id=1;
      set role authenticated;
    `);
    await assert.rejects(checkout(102, 2, unavailable.revision, 15), /precio o consumo cambió/i);
    await db.exec(`
      reset role;
      update public.products set price=10 where id=1;
      update public.products set stock=5,stock_revision=stock_revision+1 where id=4;
      create function public.fixture_fail_close() returns trigger language plpgsql as $$
      begin if new.id=2 and new.is_occupied=0 then raise exception 'close failed'; end if; return new; end $$;
      create trigger fixture_fail_close before update on public.billiard_tables
        for each row execute function public.fixture_fail_close();
      set role authenticated;
    `);
    await assert.rejects(checkout(102, 2, unavailable.revision, 15), /close failed/i);
    await db.exec('reset role');
    assert.equal((await db.query('select stock from public.products where id=1')).rows[0].stock, 13);
    assert.equal((await db.query('select stock from public.products where id=4')).rows[0].stock, 5);
    assert.equal((await db.query('select count(*)::int as n from public.sales_history')).rows[0].n, 1);
    assert.equal((await db.query('select is_occupied from public.billiard_tables where id=2')).rows[0].is_occupied, 1);
    await db.exec(`
      drop trigger fixture_fail_close on public.billiard_tables;
      update public.billar_settings set hourly_rate=1 where billar_id='A';
      set role authenticated;
    `);
    await as(1);
    await open(3, 3);
    await as(2);
    // Let the server clock advance past one whole second.
    await new Promise(resolve => setTimeout(resolve, 1200));
    const timer = await snapshot(3);
    assert.equal(timer.time_cost, 1);
    assert.equal(timer.total, 1);
    const timerResult = await checkout(103, 3, timer.revision, timer.total, timer.total, 'Billar', timer.time_cost);
    assert.match(timerResult.items[0].product_name, /^Tiempo de juego/);
    await as(1);
    await open(4, 4, 'Comanda');
    await add(13, 4, 1, 1, 10, 'Comanda');
    await as(2);
    const comanda = await snapshot(4, 'Comanda');
    await assert.rejects(checkout(104, 4, comanda.revision, 10, 6, 'Comanda'), /debe cubrir el total/i);
    const comandaResult = await checkout(104, 4, comanda.revision, 10, 10, 'Comanda');
    assert.equal(comandaResult.items.length, 1);
    assert.equal(comandaResult.paid, 10);
    await db.exec('reset role');
    assert.equal((await db.query('select source_module from public.sales_history where id=$1', [comandaResult.sale_id])).rows[0].source_module, 'dine_in');
    await db.exec(`reset role; update public.business_memberships set is_active=false where user_id='${actor(2)}'; set role authenticated`);
    await assert.rejects(checkout(100, 1, current.revision, 65, 70), /Sin permiso/i);

    await db.exec('reset role; set role authenticated');
    await as(5);
    await open(5, 5);
    await add(15, 5, 1, 1, 10);
    const pool = await snapshot(5);
    assert.equal(pool.table_id, 5);
    assert.equal(pool.total, 10);
    const poolResult = await checkout(105, 5, pool.revision, 10, 10);
    assert.equal(poolResult.total, 10);
    assert.equal(poolResult.items.length, 1);

    await as(2);
    await assert.rejects(lateSnapshot(1), /Sin permiso/i);
    await as(3);
    await assert.rejects(
      adjustLate(106, 1, 1, 10),
      /permission denied/i,
    );
    await db.exec(`reset role;
      grant execute on function public.staff_table_adjust_late_consumptions(
        uuid,text,text,uuid,bigint,double precision,text,double precision
      ) to authenticated;
      set role authenticated`);
    await as(3);
    const firstLateQuote = await lateSnapshot(1);
    assert.equal(firstLateQuote.item_count, 1);
    assert.equal(firstLateQuote.total, 10);
    await as(1);
    await add(16, 1, 1, 1, 10);
    await add(17, 1, 2, 1, 40);
    await add(18, 1, 3, 1, 15);
    await as(3);
    await assert.rejects(
      adjustLate(106, 1, firstLateQuote.revision, firstLateQuote.total),
      error => error.code === 'PST02',
    );
    const lateQuote = await lateSnapshot(1);
    assert.equal(lateQuote.item_count, 4);
    assert.equal(lateQuote.total, 75);
    await assert.rejects(
      adjustLate(106, 1, lateQuote.revision, lateQuote.total, 74),
      /debe cubrir el total/i,
    );
    await db.exec('reset role');
    const stockBeforeAdjustment = (await db.query(
      'select stock from public.products where id=1',
    )).rows[0].stock;
    await db.exec('update public.products set price=41 where id=2; set role authenticated');
    await as(3);
    await assert.rejects(
      adjustLate(107, 1, lateQuote.revision, lateQuote.total, 75),
      /precio o consumo cambió/i,
    );
    await db.exec(`reset role;
      update public.products set price=40 where id=2;
      update public.products set stock=0,stock_revision=stock_revision+1 where id=1;
      set role authenticated`);
    await as(3);
    await assert.rejects(
      adjustLate(108, 1, lateQuote.revision, lateQuote.total, 75),
      /existencias suficientes/i,
    );
    await db.exec(`reset role;
      update public.products set stock=${stockBeforeAdjustment},stock_revision=stock_revision+1 where id=1;
      create function public.fixture_fail_late_adjustment_movement() returns trigger language plpgsql as $$
      begin
        if new.notes like 'Ajuste tardio servicio %' then
          raise exception 'late adjustment rollback';
        end if;
        return new;
      end $$;
      create trigger fixture_fail_late_adjustment_movement
        before insert on public.inventory_movements
        for each row execute function public.fixture_fail_late_adjustment_movement();
      set role authenticated`);
    await as(3);
    await assert.rejects(
      adjustLate(109, 1, lateQuote.revision, lateQuote.total, 75),
      /late adjustment rollback/i,
    );
    await db.exec(`reset role;
      drop trigger fixture_fail_late_adjustment_movement on public.inventory_movements;
      drop function public.fixture_fail_late_adjustment_movement();
    `);
    assert.equal((await db.query(
      'select stock from public.products where id=1',
    )).rows[0].stock, stockBeforeAdjustment);
    const salesBeforeAdjustment = (await db.query(
      'select count(*)::int as n from public.sales_history',
    )).rows[0].n;
    const movementsBeforeAdjustment = (await db.query(
      'select count(*)::int as n from public.inventory_movements',
    )).rows[0].n;
    const originalSale = (await db.query(
      'select total, paid, cancelled from public.sales_history where id=$1',
      [result.sale_id],
    )).rows[0];
    await db.exec('set role authenticated');
    await as(3);
    const adjustment = await adjustLate(106, 1, lateQuote.revision, lateQuote.total, 75);
    assert.equal(adjustment.total, 75);
    assert.equal(adjustment.paid, 75);
    assert.equal(adjustment.items.length, 4);
    assert.equal(adjustment.service_id, service(1));
    assert.deepEqual(
      await adjustLate(106, 1, lateQuote.revision, lateQuote.total, 75),
      adjustment,
    );
    await assert.rejects(
      adjustLate(106, 1, lateQuote.revision, lateQuote.total, 76),
      /identificador del ajuste/i,
    );
    await assert.rejects(lateSnapshot(1), /no tiene consumos tardíos pendientes/i);
    const remainingConflicts = (await db.query(
      "select public.staff_table_conflicts('A','Billar',null) as data",
    )).rows[0].data;
    assert.equal(
      remainingConflicts.items.some(item => item.service_id === service(1)),
      false,
    );
    await db.exec('reset role');
    assert.equal((await db.query(
      'select count(*)::int as n from public.sales_history',
    )).rows[0].n, salesBeforeAdjustment + 1);
    assert.equal((await db.query(
      'select count(*)::int as n from public.inventory_movements',
    )).rows[0].n, movementsBeforeAdjustment + 4);
    assert.deepEqual((await db.query(
      'select total, paid, cancelled from public.sales_history where id=$1',
      [result.sale_id],
    )).rows[0], originalSale);
    assert.equal((await db.query(
      'select count(*)::int as n from public.staff_table_service_consumptions where late_adjustment_request_id=$1',
      [request(106)],
    )).rows[0].n, 4);
    assert.equal((await db.query(
      'select is_occupied from public.billiard_tables where billar_id=\'A\' and id=1',
    )).rows[0].is_occupied, 0);
  } finally {
    await db.close();
  }
});
