    with page as materialized (
        select * from public.staff_table_service_consumptions c
        where c.billar_id = requested_billar_id and c.service_id = requested_service_id
          and (c.late or exists (
              select 1 from public.staff_table_service_requests s
              where s.billar_id = c.billar_id and s.service_id = c.service_id
                and s.state = 'conflict'
          ))
          and (before_ordinal is null or c.ordinal < before_ordinal)
        order by c.ordinal desc limit 51
    )
    select coalesce((select jsonb_agg(jsonb_build_object(
        'ordinal', p.ordinal, 'request_id', p.request_id, 'product_id', p.product_id,
        'product_name', p.product_name, 'quantity', p.quantity, 'price', p.price,
        'recorded_at', p.recorded_at
    ) order by p.ordinal desc) from (select * from page order by ordinal desc limit 50) p), '[]'::jsonb),
    (select count(*) > 50 from page)
    into items, has_more;
    return jsonb_build_object('billar_id', requested_billar_id,
        'table_type', requested_table_type, 'service_id', requested_service_id,
        'items', items, 'has_more', has_more);
end;
$$;

-- Preview only: no sale, payment, stock change or table closure occurs here.
-- The revision identifies the latest immutable consumption, not the table state.
create or replace function public.staff_table_checkout_snapshot(
    requested_billar_id text, requested_table_type text, requested_service_id uuid,
    expected_revision bigint default null, before_ordinal bigint default null
)
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    permission text;
    service public.staff_table_service_requests%rowtype;
    revision bigint;
    item_count bigint;
    hourly_rate double precision;
    quoted_at timestamptz;
    time_cost numeric := 0;
    total numeric;
    items jsonb;
    has_more boolean;
begin
    if requested_billar_id is null or btrim(requested_billar_id) = ''
       or requested_table_type is null or requested_table_type not in ('Billar', 'Comanda')
       or requested_service_id is null
       or (expected_revision is not null and expected_revision < 0)
       or (before_ordinal is not null and
           (before_ordinal <= 0 or expected_revision is null)) then
        raise exception 'Consulta de cobro inválida.' using errcode = '22023';
    end if;
    permission := case requested_table_type
        when 'Billar' then 'billiard_tables_charge' else 'dine_in_charge' end;
    perform public.staff_table_require_permission(requested_billar_id, permission);

    select * into service from public.staff_table_service_requests s
    where s.service_id = requested_service_id and s.billar_id = requested_billar_id
      and s.table_type = requested_table_type and s.state = 'active'
    for share;
    if not found then
        raise exception 'El servicio activo no está disponible.' using errcode = '42501';
    end if;
    if service.actor_id is distinct from auth.uid() then
        permission := case requested_table_type
            when 'Billar' then 'billiard_tables_view_all'
            else 'dine_in_view_all'
        end;
        perform public.staff_table_require_permission(requested_billar_id, permission);
    end if;
    perform 1 from public.billiard_tables t
    where t.billar_id = service.billar_id and t.id = service.table_id
      and (
          (service.table_type = 'Billar'
              and t.table_type in ('Billar', 'Pool', 'Carambola', 'Snooker'))
          or (service.table_type = 'Comanda' and t.table_type = 'Comanda')
      )
      and t.is_deleted = 0
      and t.is_occupied = 1 and t.start_time = service.opened_at
      and (t.orders is null or btrim(t.orders) = '[]')
    for share;
    if not found then
        raise exception 'El estado de la mesa requiere revisión.' using errcode = '55000';
    end if;

    if (select count(*) from public.billar_settings s where s.billar_id = requested_billar_id) <> 1 then
        raise exception 'No hay una configuración única para este billar.' using errcode = '55000';
    end if;
    select s.hourly_rate into strict hourly_rate from public.billar_settings s
    where s.billar_id = requested_billar_id for share;
    quoted_at := clock_timestamp();
    time_cost := public.staff_table_time_cost(
        requested_table_type, service.opened_at, quoted_at, hourly_rate);
    select coalesce(max(c.ordinal), 0), count(*),
        coalesce(sum(c.quantity::numeric * c.price::numeric), 0) + time_cost
    into revision, item_count, total
    from public.staff_table_service_consumptions c
    where c.billar_id = service.billar_id and c.service_id = service.service_id;
    if expected_revision is not null and expected_revision <> revision then
        raise exception 'Los consumos cambiaron; vuelve a consultar el servicio.'
            using errcode = 'PST02';
    end if;

    with page as materialized (
        select * from public.staff_table_service_consumptions c
        where c.billar_id = service.billar_id and c.service_id = service.service_id
          and (before_ordinal is null or c.ordinal < before_ordinal)
        order by c.ordinal desc limit 51
    )
    select coalesce((select jsonb_agg(jsonb_build_object(
        'ordinal', p.ordinal, 'request_id', p.request_id, 'product_id', p.product_id,
        'product_name', p.product_name, 'quantity', p.quantity, 'price', p.price,
        'recorded_at', p.recorded_at
    ) order by p.ordinal desc) from (select * from page order by ordinal desc limit 50) p), '[]'::jsonb),
    (select count(*) > 50 from page)
    into items, has_more;
    return jsonb_build_object(
        'service_id', service.service_id, 'billar_id', service.billar_id,
        'table_id', service.table_id, 'table_type', service.table_type,
        'actor_id', service.actor_id, 'opened_at', service.opened_at,
        'revision', revision, 'item_count', item_count, 'items', items,
        'quoted_at', quoted_at, 'time_cost', time_cost::double precision,
        'total', total::double precision,
        'has_more', has_more
    );
end;
$$;

