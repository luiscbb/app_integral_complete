-- A legacy upsert must never overwrite a table with a confirmed staff service.
-- The guarded UI and atomic checkout are still required before deployment.
create or replace function public.staff_table_guard_legacy_write()
returns trigger language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
begin
    if exists (
        select 1 from public.staff_table_service_requests s
        where s.billar_id = old.billar_id and s.table_id = old.id
          and s.state = 'active'
    ) then
        if tg_op = 'DELETE' then
            raise exception 'La mesa tiene un servicio de personal activo; no se puede sobrescribir.'
                using errcode = 'PST01';
        end if;
        if new is distinct from old then
            raise exception 'La mesa tiene un servicio de personal activo; no se puede sobrescribir.'
                using errcode = 'PST01';
        end if;
    end if;
    if tg_op = 'DELETE' then return old; end if;
    return new;
end;
$$;
revoke all on function public.staff_table_guard_legacy_write()
    from public, anon, authenticated;
drop trigger if exists billiard_tables_staff_active_guard on public.billiard_tables;
create trigger billiard_tables_staff_active_guard
    before update or delete on public.billiard_tables
    for each row execute function public.staff_table_guard_legacy_write();

-- Internal only. The lock prevents a concurrent membership revocation from
-- committing in the middle of an operation.
create or replace function public.staff_table_require_permission(
    requested_billar_id text, requested_permission text
)
returns void language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
begin
    perform 1 from public.business_memberships m
    where m.user_id = auth.uid() and m.billar_id = requested_billar_id
      and m.is_active and not m.must_change_password
      and (m.role = 'admin' or (
          m.role = 'manager' and m.username is not null
          and requested_permission = any(m.allowed_modules)
          and (
              (
                  requested_permission in (
                      'billiard_tables_open', 'billiard_tables_consume',
                      'billiard_tables_charge', 'billiard_tables_view_all'
                  )
                  and 'billiard_tables' = any(m.allowed_modules)
              )
              or (
                  requested_permission in (
                      'dine_in_open', 'dine_in_consume',
                      'dine_in_charge', 'dine_in_view_all'
                  )
                  and 'dine_in' = any(m.allowed_modules)
              )
          )
      ))
    for share;
    if not found then
        raise exception 'Sin permiso para esta operación de servicio.' using errcode = '42501';
    end if;
end;
$$;
revoke all on function public.staff_table_require_permission(text,text)
    from public, anon, authenticated;

create or replace function public.staff_table_time_cost(
    requested_table_type text, opened_at timestamptz, quoted_at timestamptz,
    hourly_rate double precision
)
returns numeric language plpgsql immutable
set search_path = pg_catalog, public, pg_temp
as $$
begin
    if requested_table_type is null or requested_table_type not in ('Billar', 'Comanda')
       or opened_at is null or not isfinite(opened_at)
       or quoted_at is null or not isfinite(quoted_at) or opened_at > quoted_at
       or (hourly_rate >= 0 and hourly_rate < 'Infinity'::double precision) is not true then
        raise exception 'La hora de apertura o tarifa requiere revisión.' using errcode = '55000';
    end if;
    if requested_table_type = 'Comanda' then return 0; end if;
    return ceil(floor(extract(epoch from quoted_at - opened_at)) * hourly_rate::numeric / 3600);
end;
$$;
revoke all on function public.staff_table_time_cost(text,timestamptz,timestamptz,double precision)
    from public, anon, authenticated;

create or replace function public.staff_table_open(
    requested_service_id uuid, requested_billar_id text, requested_table_id bigint,
    requested_table_type text, requested_opened_at timestamptz
)
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    actor uuid := auth.uid();
    service public.staff_table_service_requests%rowtype;
    target public.billiard_tables%rowtype;
    permission text;
begin
    if requested_service_id is null or requested_billar_id is null
       or btrim(requested_billar_id) = '' or requested_table_id is null
       or requested_table_id <= 0 or requested_table_type is null
       or requested_table_type not in ('Billar', 'Comanda')
       or requested_opened_at is null or not isfinite(requested_opened_at) then
        raise exception 'Datos de apertura inválidos.' using errcode = '22023';
    end if;
    permission := case requested_table_type
        when 'Billar' then 'billiard_tables_open' else 'dine_in_open' end;
    perform public.staff_table_require_permission(requested_billar_id, permission);

    insert into public.staff_table_service_requests
        (service_id, billar_id, actor_id, table_id, table_type, opened_at, state)
    values
        (requested_service_id, requested_billar_id, actor, requested_table_id,
         requested_table_type, requested_opened_at, 'pending')
    on conflict (service_id) do nothing;
    select * into strict service from public.staff_table_service_requests
        where service_id = requested_service_id for update;
    if service.billar_id is distinct from requested_billar_id
       or service.actor_id is distinct from actor
       or service.table_id is distinct from requested_table_id
       or service.table_type is distinct from requested_table_type
       or service.opened_at is distinct from requested_opened_at then
        raise exception 'El identificador de apertura ya fue utilizado.' using errcode = '23505';
    end if;
    if service.state = 'pending' then
        select * into target from public.billiard_tables
        where billar_id = requested_billar_id and id = requested_table_id for update;
        if not found or target.is_deleted <> 0
           or not (
               (requested_table_type = 'Billar'
                   and target.table_type in ('Billar', 'Pool', 'Carambola', 'Snooker'))
               or (requested_table_type = 'Comanda' and target.table_type = 'Comanda')
           )
           or target.is_occupied <> 0 or target.start_time is not null
           or (target.orders is not null and btrim(target.orders) <> '[]') then
            update public.staff_table_service_requests
                set state = 'conflict', confirmed_at = clock_timestamp()
                where service_id = requested_service_id returning * into service;
        else
            update public.billiard_tables
                set is_occupied = 1, start_time = requested_opened_at
                where billar_id = requested_billar_id and id = requested_table_id;
            update public.staff_table_service_requests
                set state = 'active', confirmed_at = clock_timestamp()
                where service_id = requested_service_id returning * into service;
        end if;
    end if;
    return jsonb_build_object(
        'service_id', service.service_id, 'billar_id', service.billar_id,
        'actor_id', service.actor_id, 'table_id', service.table_id,
        'table_type', service.table_type, 'opened_at', service.opened_at,
        'state', service.state
    );
end;
$$;

create or replace function public.staff_table_add_consumption(
    requested_request_id uuid, requested_billar_id text, requested_service_id uuid,
    requested_table_type text,
    requested_product_id bigint, requested_product_name text,
    requested_quantity double precision, requested_price double precision,
    requested_recorded_at timestamptz
)
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    actor uuid := auth.uid();
    service public.staff_table_service_requests%rowtype;
    item public.staff_table_service_consumptions%rowtype;
    permission text;
begin
    if requested_request_id is null or requested_service_id is null
       or requested_billar_id is null or btrim(requested_billar_id) = ''
       or requested_table_type is null or requested_table_type not in ('Billar', 'Comanda')
       or requested_product_id is null or requested_product_id <= 0
       or requested_product_name is null or length(btrim(requested_product_name)) not between 1 and 255
       or (requested_quantity > 0 and requested_quantity < 'Infinity'::double precision) is not true
       or (requested_price >= 0 and requested_price < 'Infinity'::double precision) is not true
       or requested_recorded_at is null or not isfinite(requested_recorded_at) then
        raise exception 'Datos de consumo inválidos.' using errcode = '22023';
    end if;
    permission := case requested_table_type
        when 'Billar' then 'billiard_tables_consume' else 'dine_in_consume' end;
    perform public.staff_table_require_permission(requested_billar_id, permission);
    select * into service from public.staff_table_service_requests
    where service_id = requested_service_id and billar_id = requested_billar_id
      and table_type = requested_table_type for update;
    if not found or service.actor_id is distinct from actor
       or service.state not in ('active', 'conflict', 'closed') then
        raise exception 'El servicio no está disponible.' using errcode = '42501';
    end if;
    insert into public.staff_table_service_consumptions (
        request_id, service_id, billar_id, actor_id, product_id, product_name,
        quantity, price, recorded_at, late
    ) values (
        requested_request_id, requested_service_id, requested_billar_id, actor,
        requested_product_id, btrim(requested_product_name), requested_quantity,
        requested_price, requested_recorded_at, service.state = 'closed'
    ) on conflict (request_id) do nothing;
    select * into strict item from public.staff_table_service_consumptions
        where request_id = requested_request_id for update;
    if item.service_id is distinct from requested_service_id
       or item.billar_id is distinct from requested_billar_id
       or item.actor_id is distinct from actor
       or item.product_id is distinct from requested_product_id
       or item.product_name is distinct from btrim(requested_product_name)
       or item.quantity is distinct from requested_quantity
       or item.price is distinct from requested_price
       or item.recorded_at is distinct from requested_recorded_at then
        raise exception 'El identificador de consumo ya fue utilizado.' using errcode = '23505';
    end if;
    return jsonb_build_object(
        'request_id', item.request_id, 'service_id', item.service_id,
        'billar_id', item.billar_id, 'actor_id', item.actor_id,
        'product_id', item.product_id, 'product_name', item.product_name,
        'quantity', item.quantity, 'price', item.price, 'recorded_at', item.recorded_at,
        'service_state', service.state, 'late', item.late
    );
end;
$$;

create or replace function public.staff_table_visible_tables(
    requested_billar_id text, requested_table_type text
)
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    actor uuid := auth.uid();
    membership public.business_memberships%rowtype;
    view_all_permission text;
    can_view_all boolean;
    items jsonb;
begin
    if actor is null or requested_billar_id is null
       or btrim(requested_billar_id) = ''
       or requested_table_type is null
       or requested_table_type not in ('Billar', 'Comanda') then
        raise exception 'Consulta de mesas inválida.' using errcode = '22023';
    end if;

    view_all_permission := case requested_table_type
        when 'Billar' then 'billiard_tables_view_all'
        else 'dine_in_view_all'
    end;
    select * into membership
    from public.business_memberships m
    where m.user_id = actor and m.billar_id = requested_billar_id
      and m.is_active and not m.must_change_password
      and (
          m.role = 'admin'
          or (
              m.role = 'manager' and m.username is not null
              and case requested_table_type
                  when 'Billar' then 'billiard_tables' = any(m.allowed_modules)
                  else 'dine_in' = any(m.allowed_modules)
              end
              and m.allowed_modules && case requested_table_type
                  when 'Billar' then array[
                      'billiard_tables_open', 'billiard_tables_consume',
                      'billiard_tables_charge', 'billiard_tables_view_all'
                  ]::text[]
                  else array[
                      'dine_in_open', 'dine_in_consume',
                      'dine_in_charge', 'dine_in_view_all'
                  ]::text[]
              end
          )
      )
    for share;
    if not found then
        raise exception 'Sin permiso para consultar estas mesas.' using errcode = '42501';
    end if;

    can_view_all := membership.role = 'admin'
        or view_all_permission = any(membership.allowed_modules);
    select coalesce(jsonb_agg(jsonb_build_object(
        'id', t.id,
        'billar_id', t.billar_id,
        'name', t.name,
        'table_type', t.table_type,
        'is_occupied', t.is_occupied,
        'start_time', t.start_time,
        'orders', case
            when service.service_id is not null then service_items.items::text
            else coalesce(t.orders, '[]')
        end,
        'is_deleted', t.is_deleted,
        'service_id', service.service_id,
        'service_actor_id', service.actor_id,
        'service_state', service.state,
        'service_items', service_items.items
    ) order by t.id), '[]'::jsonb)
    into items
    from public.billiard_tables t
    left join lateral (
        select s.service_id, s.actor_id, s.state
        from public.staff_table_service_requests s
        where s.billar_id = t.billar_id and s.table_id = t.id
          and s.state = 'active'
        limit 1
    ) service on true
    left join lateral (
        select coalesce(jsonb_agg(jsonb_build_object(
            'request_id', c.request_id,
            'productId', c.product_id,
            'productName', c.product_name,
            'price', c.price,
            'quantity', c.quantity,
            'recorded_at', c.recorded_at
        ) order by c.ordinal), '[]'::jsonb) as items
        from public.staff_table_service_consumptions c
        where c.billar_id = t.billar_id
          and c.service_id = service.service_id
    ) service_items on true
    where t.billar_id = requested_billar_id and t.is_deleted = 0
      and (
          (requested_table_type = 'Comanda' and t.table_type = 'Comanda')
          or (
              requested_table_type = 'Billar'
              and t.table_type in ('Billar', 'Pool', 'Carambola', 'Snooker')
          )
      )
      and (
          can_view_all
          or service.actor_id = actor
          or (
              service.service_id is null
              and t.is_occupied = 0
              and t.start_time is null
              and (t.orders is null or btrim(t.orders) in ('', '[]'))
          )
      );

    return jsonb_build_object(
        'billar_id', requested_billar_id,
        'table_type', requested_table_type,
        'items', items
    );
end;
$$;

create or replace function public.staff_table_conflicts(
    requested_billar_id text, requested_table_type text, before_ordinal bigint default null
)
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    permission text;
    items jsonb;
    has_more boolean;
begin
    if requested_billar_id is null or btrim(requested_billar_id) = ''
       or requested_table_type is null or requested_table_type not in ('Billar', 'Comanda')
       or (before_ordinal is not null and before_ordinal <= 0) then
        raise exception 'Consulta de conflictos inválida.' using errcode = '22023';
    end if;
    permission := case requested_table_type
        when 'Billar' then 'billiard_tables_view_all' else 'dine_in_view_all' end;
    perform public.staff_table_require_permission(requested_billar_id, permission);
    with page as materialized (
        select * from public.staff_table_service_requests s
        where s.billar_id = requested_billar_id and s.table_type = requested_table_type
          and (s.state = 'conflict' or (s.state = 'closed' and exists (
              select 1 from public.staff_table_service_consumptions c
              where c.billar_id = s.billar_id and c.service_id = s.service_id
                and c.late
          )))
          and (before_ordinal is null or s.ordinal < before_ordinal)
        order by s.ordinal desc limit 51
    )
    select coalesce((select jsonb_agg(jsonb_build_object(
        'ordinal', p.ordinal, 'service_id', p.service_id, 'billar_id', p.billar_id,
        'actor_id', p.actor_id, 'table_id', p.table_id, 'table_type', p.table_type,
        'opened_at', p.opened_at,
        'reason', case when p.state = 'closed' then 'late_consumption' else 'opening' end
    ) order by p.ordinal desc) from (select * from page order by ordinal desc limit 50) p), '[]'::jsonb),
    (select count(*) > 50 from page)
    into items, has_more;
    return jsonb_build_object('billar_id', requested_billar_id,
        'table_type', requested_table_type, 'items', items, 'has_more', has_more);
end;
$$;

create or replace function public.staff_table_conflict_consumptions(
    requested_billar_id text, requested_table_type text,
    requested_service_id uuid, before_ordinal bigint default null
)
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
    permission text;
    items jsonb;
    has_more boolean;
begin
    if requested_billar_id is null or btrim(requested_billar_id) = ''
       or requested_table_type is null or requested_table_type not in ('Billar', 'Comanda')
       or requested_service_id is null
       or (before_ordinal is not null and before_ordinal <= 0) then
        raise exception 'Consulta de consumos inválida.' using errcode = '22023';
    end if;
    permission := case requested_table_type
        when 'Billar' then 'billiard_tables_view_all' else 'dine_in_view_all' end;
