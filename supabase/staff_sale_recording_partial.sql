-- Partial preparation only: do not deploy or enable staff accounts yet.
-- Quick-sale inventory is recorded here, but reservations, other POS modules,
-- concurrent legacy stock sync and the client flow are not yet integrated.
-- Requires add_staff_account_fields.sql, add_sales_origin.sql and
-- product_stock_conflict_guard_partial.sql.
begin;

create table if not exists public.staff_sale_requests (
    billar_id text not null,
    request_id uuid not null,
    actor_id uuid not null,
    request_payload jsonb not null,
    sale_id bigint,
    completed boolean not null default false,
    primary key (billar_id, request_id)
);

alter table public.staff_sale_requests enable row level security;
revoke all on public.staff_sale_requests from public, anon, authenticated;

create table if not exists public.staff_sale_stock_products (
    billar_id text not null,
    request_id uuid not null,
    product_id bigint not null references public.products(id) on delete restrict,
    primary key (billar_id, request_id, product_id),
    foreign key (billar_id, request_id)
        references public.staff_sale_requests(billar_id, request_id) on delete restrict
);
alter table public.staff_sale_stock_products enable row level security;
revoke all on public.staff_sale_stock_products from public, anon, authenticated;

create table if not exists public.staff_sale_audit (
    id bigint generated by default as identity primary key,
    billar_id text not null,
    actor_id uuid not null,
    sale_id bigint not null,
    created_at timestamptz not null default now()
);

alter table public.staff_sale_audit enable row level security;
revoke all on public.staff_sale_audit from public, anon, authenticated;
grant select on public.staff_sale_audit to authenticated;

drop policy if exists "staff_sale_audit_admin_select" on public.staff_sale_audit;
create policy "staff_sale_audit_admin_select" on public.staff_sale_audit
for select to authenticated
using (public.has_billar_role(billar_id, array['admin']::text[]));

create or replace function public.record_staff_sale(
    p_request_id uuid,
    p_billar_id text,
    p_source_module text,
    p_sale_type text,
    p_sale_date text,
    p_payment_method text,
    p_total double precision,
    p_paid double precision,
    p_customer_key text,
    p_items jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    actor uuid := auth.uid();
    request_payload jsonb;
    request_row public.staff_sale_requests%rowtype;
    new_sale_id bigint;
    item jsonb;
    item_product_id bigint;
    item_cost double precision;
    item_quantity numeric;
    item_price numeric;
    calculated_total numeric := 0;
    allow_negative boolean;
    product_row public.products%rowtype;
    component record;
    component_count integer;
    stock_quantity double precision;
begin
    if actor is null then
        raise exception 'Se requiere una sesión autenticada.' using errcode = '42501';
    end if;
    if p_request_id is null or p_billar_id is null or btrim(p_billar_id) = ''
       or p_source_module is null or p_source_module not in
           ('quick_sale', 'billiard_tables', 'dine_in', 'personal_account')
       or p_sale_type is null or btrim(p_sale_type) = ''
       or p_sale_date is null or btrim(p_sale_date) = ''
       or p_payment_method is null or btrim(p_payment_method) = ''
       or (p_total >= 0 and p_total < 'Infinity'::double precision) is not true
       or (p_paid >= 0 and p_paid < 'Infinity'::double precision) is not true
       or p_items is null or jsonb_typeof(p_items) <> 'array' then
        raise exception 'Datos de venta inválidos.' using errcode = '22023';
    end if;
    if jsonb_array_length(p_items) = 0 then
        raise exception 'La venta debe tener al menos un detalle.' using errcode = '22023';
    end if;
    if p_source_module <> 'quick_sale' or p_sale_type <> 'Venta Rápida'
       or p_customer_key is not null then
        raise exception 'Este módulo de venta aún no está habilitado.' using errcode = '42501';
    end if;

    perform 1
    from public.business_memberships membership
    where membership.user_id = actor
      and membership.billar_id = p_billar_id
      and membership.is_active
      and not membership.must_change_password
      and membership.role = 'manager'
      and membership.username is not null
      and p_source_module = any (membership.allowed_modules)
    for share;
    if not found then
        raise exception 'No tienes permiso para registrar esta venta.' using errcode = '42501';
    end if;

    request_payload := jsonb_build_object(
        'source_module', p_source_module, 'sale_type', p_sale_type,
        'sale_date', p_sale_date, 'payment_method', p_payment_method,
        'total', p_total, 'paid', p_paid, 'customer_key', p_customer_key,
        'items', p_items
    );
    insert into public.staff_sale_requests (billar_id, request_id, actor_id, request_payload)
    values (p_billar_id, p_request_id, actor, request_payload)
    on conflict (billar_id, request_id) do nothing;

    select * into strict request_row
    from public.staff_sale_requests
    where billar_id = p_billar_id and request_id = p_request_id
    for update;
    if request_row.actor_id <> actor or request_row.request_payload <> request_payload then
        raise exception 'El identificador de venta ya fue utilizado.' using errcode = '23505';
    end if;
    if request_row.completed then
        if not exists (select 1 from public.sales_history sale where sale.id = request_row.sale_id) then
            raise exception 'La venta registrada ya no está disponible.' using errcode = '55000';
        end if;
        return request_row.sale_id;
    end if;

    if (select count(*) from public.billar_settings where billar_id = p_billar_id) <> 1 then
        raise exception 'No hay una configuración única para este billar.' using errcode = '55000';
    end if;
    select settings.allow_negative_stock_sales into strict allow_negative
    from public.billar_settings settings
    where settings.billar_id = p_billar_id;

    insert into public.sales_history (
        billar_id, type, source_module, date, payment_method, total, paid, customer_key, cancelled
    ) values (
        p_billar_id, p_sale_type, p_source_module, p_sale_date, p_payment_method,
        p_total, p_paid, p_customer_key, false
    ) returning id into new_sale_id;

    for item in select value from jsonb_array_elements(p_items)
    loop
        if jsonb_typeof(item) <> 'object'
           or jsonb_typeof(item -> 'product_name') is distinct from 'string'
           or btrim(item ->> 'product_name') = ''
           or jsonb_typeof(item -> 'quantity') is distinct from 'number'
           or jsonb_typeof(item -> 'price_at_sale') is distinct from 'number' then
            raise exception 'Detalle de venta inválido.' using errcode = '22023';
        end if;
        item_quantity := (item ->> 'quantity')::numeric;
        item_price := (item ->> 'price_at_sale')::numeric;
        if item_quantity <= 0 or item_price < 0 then
            raise exception 'Cantidad o precio inválido.' using errcode = '22023';
        end if;
        calculated_total := calculated_total + item_quantity * item_price;

        if jsonb_typeof(item -> 'product_id') is distinct from 'number'
           or (item ->> 'product_id')::numeric <> trunc((item ->> 'product_id')::numeric) then
            raise exception 'Producto inválido.' using errcode = '22023';
        end if;
        item_product_id := (item ->> 'product_id')::bigint;
        select * into product_row from public.products product
        where product.id = item_product_id and product.billar_id = p_billar_id
          and product.is_active
        for update;
        if not found then
            raise exception 'El producto no pertenece a este billar o no está activo.'
                using errcode = '42501';
        end if;
        if abs(item_price - product_row.price::numeric) > 0.000001 then
            raise exception 'El precio del producto cambió; actualiza el inventario.'
                using errcode = '22023';
        end if;
        item_cost := coalesce(product_row.cost, 0);

        if product_row.parent_id is not null then
            if product_row.pieces_per_unit <= 0 then
                raise exception 'La presentación del producto es inválida.' using errcode = '22023';
            end if;
            stock_quantity := (item_quantity * product_row.pieces_per_unit)::double precision;
            update public.products
            set stock = stock - stock_quantity, stock_revision = stock_revision + 1
            where id = product_row.parent_id and billar_id = p_billar_id
              and parent_id is null and is_promo = 0 and is_active
              and (allow_negative or stock >= stock_quantity);
            if not found then
                raise exception 'No hay existencias suficientes o el producto padre es inválido.'
                    using errcode = '22023';
            end if;
            insert into public.staff_sale_stock_products (billar_id, request_id, product_id)
            values (p_billar_id, p_request_id, product_row.parent_id)
            on conflict do nothing;
        elsif product_row.is_promo = 1 then
            component_count := 0;
            for component in
                select child_id, quantity from public.promo_items
                where parent_id = item_product_id
                order by child_id
                for share
            loop
                component_count := component_count + 1;
                if component.quantity <= 0 then
                    raise exception 'La promoción contiene cantidades inválidas.' using errcode = '22023';
                end if;
                stock_quantity := (item_quantity * component.quantity)::double precision;
                update public.products
                set stock = stock - stock_quantity, stock_revision = stock_revision + 1
                where id = component.child_id and billar_id = p_billar_id
                  and parent_id is null and is_promo = 0 and is_active
                  and (allow_negative or stock >= stock_quantity);
                if not found then
                    raise exception 'No hay existencias suficientes para la promoción.'
                        using errcode = '22023';
                end if;
                insert into public.staff_sale_stock_products (billar_id, request_id, product_id)
                values (p_billar_id, p_request_id, component.child_id)
                on conflict do nothing;
            end loop;
            if component_count = 0 then
                raise exception 'La promoción no tiene componentes.' using errcode = '22023';
            end if;
        else
            stock_quantity := item_quantity::double precision;
            update public.products
            set stock = stock - stock_quantity, stock_revision = stock_revision + 1
            where id = item_product_id and billar_id = p_billar_id
              and (allow_negative or stock >= stock_quantity);
            if not found then
                raise exception 'No hay existencias suficientes.' using errcode = '22023';
            end if;
            insert into public.staff_sale_stock_products (billar_id, request_id, product_id)
            values (p_billar_id, p_request_id, item_product_id)
            on conflict do nothing;
        end if;

        insert into public.sale_details (
            sale_id, product_id, product_name, quantity, price_at_sale, cost_at_sale, cancelled
        ) values (
            new_sale_id, item_product_id, product_row.name,
            item_quantity::double precision, item_price::double precision, item_cost, false
        );
        insert into public.inventory_movements (
            billar_id, product_id, movement_type, quantity, unit_cost,
            unit_price, reference_id, reference_type, notes
        ) values (
            p_billar_id, item_product_id, 'sale', -item_quantity::double precision,
            item_cost, item_price::double precision, new_sale_id, 'sales_history', 'Venta rápida'
        );
    end loop;

    if abs(calculated_total - p_total::numeric)
       > greatest(0.000001::numeric, abs(calculated_total) * 0.0000000001::numeric) then
        raise exception 'El total no coincide con los detalles.' using errcode = '22023';
    end if;

    insert into public.staff_sale_audit (billar_id, actor_id, sale_id)
    values (p_billar_id, actor, new_sale_id);
    update public.staff_sale_requests
    set sale_id = new_sale_id, completed = true
    where billar_id = p_billar_id and request_id = p_request_id;
    return new_sale_id;
end;
$$;

revoke all on function public.record_staff_sale(
    uuid, text, text, text, text, text, double precision, double precision, text, jsonb
) from public, anon, authenticated;

create or replace function public.get_staff_sale_reconciliation(
    p_request_id uuid,
    p_billar_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    result jsonb;
    may_view_cost boolean;
begin
    if auth.uid() is null or p_request_id is null or p_billar_id is null
       or btrim(p_billar_id) = '' then
        raise exception 'Datos de recuperación inválidos.' using errcode = '42501';
    end if;
    perform 1 from public.business_memberships membership
    where membership.user_id = auth.uid()
      and membership.billar_id = p_billar_id
      and membership.is_active and not membership.must_change_password
      and membership.role = 'manager' and membership.username is not null
      and 'quick_sale' = any(membership.allowed_modules)
    for share;
    if not found then
        raise exception 'No tienes permiso para recuperar esta venta.' using errcode = '42501';
    end if;
    select 'reports' = any(membership.allowed_modules) into strict may_view_cost
    from public.business_memberships membership
    where membership.user_id = auth.uid() and membership.billar_id = p_billar_id
      and membership.is_active and not membership.must_change_password
      and membership.role = 'manager' and membership.username is not null
      and 'quick_sale' = any(membership.allowed_modules);
    select jsonb_build_object(
        'request_id', request.request_id,
        'billar_id', request.billar_id,
        'sale_id', sale.id,
        'date', sale.date,
        'payment_method', sale.payment_method,
        'total', sale.total,
        'paid', sale.paid,
        'cancelled', sale.cancelled,
        'items', (
            select coalesce(jsonb_agg((jsonb_build_object(
                'product_id', detail.product_id, 'product_name', detail.product_name,
                'quantity', detail.quantity, 'price_at_sale', detail.price_at_sale,
                'cancelled', detail.cancelled
            ) || case when may_view_cost then
                jsonb_build_object('cost_at_sale', detail.cost_at_sale)
                else '{}'::jsonb end) order by detail.id), '[]'::jsonb)
            from public.sale_details detail where detail.sale_id = sale.id
        ),
        'stock', (
            select coalesce(jsonb_agg(jsonb_build_object(
                'product_id', product.id, 'stock', product.stock,
                'stock_revision', product.stock_revision
            ) order by product.id), '[]'::jsonb)
            from public.staff_sale_stock_products changed
            join public.products product on product.id = changed.product_id
                and product.billar_id = changed.billar_id
            where changed.billar_id = request.billar_id
                and changed.request_id = request.request_id
        )
    ) into result
    from public.staff_sale_requests request
    join public.sales_history sale on sale.id = request.sale_id
        and sale.billar_id = request.billar_id
    where request.billar_id = p_billar_id and request.request_id = p_request_id
      and request.actor_id = auth.uid() and request.completed;
    if result is null or jsonb_array_length(result -> 'items') = 0
       or jsonb_array_length(result -> 'stock') = 0
       or jsonb_array_length(result -> 'stock') <> (
           select count(*) from public.staff_sale_stock_products changed
           where changed.billar_id = p_billar_id and changed.request_id = p_request_id
       ) then
        raise exception 'No se encontró una venta recuperable.' using errcode = '55000';
    end if;
    return result;
end;
$$;
revoke all on function public.get_staff_sale_reconciliation(uuid, text)
    from public, anon, authenticated;

commit;
