create or replace function public.reserve_staff_account(
    p_request_id uuid,
    p_actor_id uuid,
    p_billar_id text,
    p_username text,
    p_full_name text,
    p_job_title text,
    p_modules text[],
    p_email text,
    p_key_fingerprint text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    expected_email text;
    request_row public.staff_account_requests%rowtype;
begin
    if p_request_id is null or p_actor_id is null
       or p_billar_id is null or btrim(p_billar_id) = ''
       or p_username is null or p_username !~ '^[a-z0-9][a-z0-9._-]{2,31}$'
       or p_full_name is null or length(btrim(p_full_name)) not between 1 and 120
       or p_job_title is null or length(btrim(p_job_title)) not between 1 and 80
       or p_modules is null or cardinality(p_modules) = 0
       or array_position(p_modules, null) is not null
       or not p_modules <@ array[
           'quick_sale', 'billiard_tables', 'dine_in', 'personal_account',
           'inventory', 'purchases', 'reports', 'players', 'settings'
       ]::text[]
       or p_key_fingerprint is null or p_key_fingerprint !~ '^[a-f0-9]{64}$' then
        raise exception 'Datos de personal inválidos.' using errcode = '22023';
    end if;

    perform 1 from public.business_memberships membership
    where membership.user_id = p_actor_id and membership.billar_id = p_billar_id
      and membership.is_active and not membership.must_change_password
      and membership.role = 'admin'
    for share;
    if not found then
        raise exception 'Solo un administrador activo puede crear personal.'
            using errcode = '42501';
    end if;

    expected_email := encode(convert_to(p_username, 'UTF8'), 'hex')
        || '@staff.baumar.invalid';
    if p_email is distinct from expected_email then
        raise exception 'Identificador de autenticación inválido.' using errcode = '22023';
    end if;
    insert into public.staff_account_requests (
        request_id, actor_id, billar_id, username, full_name, job_title,
        allowed_modules, email, key_fingerprint
    ) values (
        p_request_id, p_actor_id, p_billar_id, p_username, btrim(p_full_name), btrim(p_job_title),
        p_modules, p_email, p_key_fingerprint
    ) on conflict (request_id) do nothing;
    select * into strict request_row
    from public.staff_account_requests where request_id = p_request_id for update;
    if request_row.actor_id is distinct from p_actor_id
       or request_row.billar_id is distinct from p_billar_id
       or request_row.username is distinct from p_username
       or request_row.full_name is distinct from btrim(p_full_name)
       or request_row.job_title is distinct from btrim(p_job_title)
       or request_row.allowed_modules is distinct from p_modules
       or request_row.email is distinct from p_email
       or request_row.key_fingerprint is distinct from p_key_fingerprint then
        raise exception 'La solicitud ya fue utilizada con otros datos.' using errcode = '22023';
    end if;
    return jsonb_build_object('completed', request_row.completed);
end;
$$;

create or replace function public.find_staff_creation_auth_user(
    p_request_id uuid,
    p_actor_id uuid,
    p_billar_id text
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    request_row public.staff_account_requests%rowtype;
    auth_user auth.users%rowtype;
begin
    perform 1 from public.business_memberships membership
    where membership.user_id = p_actor_id and membership.billar_id = p_billar_id
      and membership.is_active and not membership.must_change_password and membership.role = 'admin'
    for share;
    if not found then
        raise exception 'Solo un administrador activo puede crear personal.' using errcode = '42501';
    end if;
    select * into request_row from public.staff_account_requests
    where request_id = p_request_id and actor_id = p_actor_id and billar_id = p_billar_id;
    if not found then
        raise exception 'La solicitud no está disponible.' using errcode = '42501';
    end if;
    select * into auth_user from auth.users where email = request_row.email;
    if not found then return null; end if;
    if auth_user.raw_app_meta_data->>'account_type' is distinct from 'staff'
       or auth_user.raw_app_meta_data->>'billar_id' is distinct from p_billar_id
       or auth_user.raw_app_meta_data->>'creation_request_id' is distinct from p_request_id::text then
        raise exception 'El usuario ya está registrado.' using errcode = '23505';
    end if;
    return auth_user.id;
end;
$$;

create or replace function public.finalize_staff_account(
    p_request_id uuid,
    p_actor_id uuid,
    p_billar_id text,
    p_user_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    request_row public.staff_account_requests%rowtype;
    staff_row public.business_memberships%rowtype;
begin
    perform 1 from public.business_memberships membership
    where membership.user_id = p_actor_id and membership.billar_id = p_billar_id
      and membership.is_active and not membership.must_change_password and membership.role = 'admin'
    for share;
    if not found then
        raise exception 'Solo un administrador activo puede crear personal.' using errcode = '42501';
    end if;
    select * into request_row from public.staff_account_requests
    where request_id = p_request_id and actor_id = p_actor_id and billar_id = p_billar_id
    for update;
    if not found then
        raise exception 'La solicitud no está disponible.' using errcode = '42501';
    end if;
    if p_user_id is null or p_user_id = p_actor_id
       or public.find_staff_creation_auth_user(p_request_id, p_actor_id, p_billar_id)
          is distinct from p_user_id then
        raise exception 'La cuenta de autenticación no coincide.' using errcode = '42501';
    end if;
    if request_row.completed then
        if request_row.user_id is distinct from p_user_id then
            raise exception 'La solicitud ya está vinculada a otra cuenta.' using errcode = '42501';
        end if;
    else
        insert into public.business_memberships (
            user_id, billar_id, email, role, is_active, must_change_password,
            created_by, username, full_name, job_title, allowed_modules
        ) values (
            p_user_id, p_billar_id, request_row.email, 'manager', true, true,
            p_actor_id, request_row.username, request_row.full_name, request_row.job_title,
            request_row.allowed_modules
        );
        insert into public.staff_account_audit (
            billar_id, actor_id, target_user_id, event_type, details
        ) values (
            p_billar_id, p_actor_id, p_user_id, 'create',
            jsonb_build_object('username', request_row.username, 'modules', to_jsonb(request_row.allowed_modules))
        );
        update public.staff_account_requests
        set user_id = p_user_id, completed = true where request_id = p_request_id;
    end if;
    select * into staff_row from public.business_memberships
    where user_id = p_user_id and billar_id = p_billar_id;
    if not found then
        raise exception 'La cuenta ya no está disponible.' using errcode = '42501';
    end if;
    return jsonb_build_object(
        'user_id', p_user_id,
        'billar_id', p_billar_id,
        'username', staff_row.username,
        'full_name', staff_row.full_name,
        'job_title', staff_row.job_title,
        'allowed_modules', to_jsonb(staff_row.allowed_modules),
        'is_active', staff_row.is_active,
        'staff_revision', staff_row.staff_revision,
        'must_change_password', staff_row.must_change_password,
        'can_deliver_password', request_row.password_recovery_allowed
            and staff_row.is_active and staff_row.must_change_password
            and staff_row.role = 'manager' and staff_row.username = request_row.username
    );
end;
$$;

create or replace function public.stop_staff_password_recovery(p_user_id uuid)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    update public.staff_account_requests
    set password_recovery_allowed = false
    where user_id = p_user_id and completed;
    return found;
end;
$$;

create or replace function public.complete_staff_password_change(
    p_user_id uuid, p_billar_id text, p_expected_revision bigint
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    staff public.business_memberships%rowtype;
begin
    if p_user_id is null or p_billar_id is null or btrim(p_billar_id) = ''
       or p_expected_revision is null or p_expected_revision < 0 then
        raise exception 'La cuenta o revisión de personal no es válida.' using errcode = '22023';
    end if;
    select * into staff from public.business_memberships membership
    where membership.user_id = p_user_id and membership.billar_id = p_billar_id
    for update;
    if not found or not staff.is_active or staff.role <> 'manager'
       or staff.username is null or not exists (
           select 1 from auth.users account where account.id = p_user_id
             and account.raw_app_meta_data ->> 'account_type' = 'staff'
             and account.raw_app_meta_data ->> 'billar_id' = p_billar_id
       ) then
        raise exception 'La cuenta de personal ya no tiene acceso activo.' using errcode = '42501';
    end if;
    if not staff.must_change_password and staff.staff_revision = p_expected_revision + 1 then
        return true;
    end if;
    if staff.staff_revision <> p_expected_revision or not staff.must_change_password then
        raise exception 'La cuenta cambió durante el cambio de contraseña.' using errcode = '40001';
    end if;
    if not exists (
        select 1 from public.staff_account_requests request
        where request.user_id = p_user_id and request.completed
          and not request.password_recovery_allowed
    ) or exists (
        select 1 from public.staff_account_requests request
        where request.user_id = p_user_id and request.completed
          and request.password_recovery_allowed
    ) then
        raise exception 'No se aseguró el cambio de contraseña.' using errcode = '55000';
    end if;
    update public.business_memberships
    set must_change_password = false, staff_revision = staff_revision + 1
    where user_id = p_user_id and billar_id = p_billar_id;
    insert into public.staff_account_audit (
        billar_id, actor_id, target_user_id, event_type, details
    ) values (
        p_billar_id, p_user_id, p_user_id, 'password_changed',
        jsonb_build_object('staff_revision', staff.staff_revision + 1)
    );
    return true;
end;
$$;

create or replace function public.list_staff_accounts(p_billar_id text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    result jsonb;
begin
    perform 1 from public.business_memberships membership
    where membership.user_id = auth.uid() and membership.billar_id = p_billar_id
      and membership.is_active and not membership.must_change_password
      and membership.role = 'admin'
    for share;
    if not found then
        raise exception 'Solo un administrador activo puede consultar personal.'
            using errcode = '42501';
    end if;
    select coalesce(jsonb_agg(jsonb_build_object(
        'user_id', staff.user_id, 'billar_id', staff.billar_id,
        'username', staff.username, 'full_name', staff.full_name,
        'job_title', staff.job_title, 'allowed_modules', to_jsonb(staff.allowed_modules),
        'is_active', staff.is_active, 'must_change_password', staff.must_change_password,
        'staff_revision', staff.staff_revision
    ) order by staff.full_name, staff.username), '[]'::jsonb) into result
    from public.business_memberships staff
    where staff.billar_id = p_billar_id and staff.role = 'manager'
      and staff.username is not null;
    return result;
end;
$$;

drop function if exists public.update_staff_account(uuid, text, uuid, text, text, text[], boolean);
create or replace function public.update_staff_account(
    p_actor_id uuid,
    p_billar_id text,
    p_user_id uuid,
    p_full_name text,
    p_job_title text,
    p_modules text[],
    p_is_active boolean,
    p_expected_revision bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    staff_row public.business_memberships%rowtype;
    normalized_modules text[];
    previous jsonb;
begin
    if p_actor_id is null or p_user_id is null or p_actor_id = p_user_id
       or p_billar_id is null or btrim(p_billar_id) = ''
       or p_full_name is null or length(btrim(p_full_name)) not between 1 and 120
       or p_job_title is null or length(btrim(p_job_title)) not between 1 and 80
       or p_modules is null or cardinality(p_modules) = 0
       or array_position(p_modules, null) is not null
       or not p_modules <@ array[
           'quick_sale', 'billiard_tables', 'dine_in', 'personal_account',
           'inventory', 'purchases', 'reports', 'players', 'settings'
       ]::text[]
       or p_is_active is null or p_expected_revision is null or p_expected_revision < 0 then
        raise exception 'Datos de personal inválidos.' using errcode = '22023';
    end if;

    perform 1 from public.business_memberships membership
    where membership.user_id = p_actor_id and membership.billar_id = p_billar_id
      and membership.is_active and not membership.must_change_password
      and membership.role = 'admin'
    for share;
    if not found then
        raise exception 'Solo un administrador activo puede gestionar personal.'
            using errcode = '42501';
    end if;

    select * into staff_row from public.business_memberships
    where user_id = p_user_id and billar_id = p_billar_id
      and role = 'manager' and username is not null
    for update;
    if not found then
        raise exception 'No se encontró la cuenta de personal.' using errcode = '42501';
    end if;
    select array_agg(distinct module order by module) into normalized_modules
    from unnest(p_modules) module;

    if staff_row.full_name is distinct from btrim(p_full_name)
       or staff_row.job_title is distinct from btrim(p_job_title)
       or (select array_agg(distinct module order by module)
           from unnest(staff_row.allowed_modules) module) is distinct from normalized_modules
       or staff_row.is_active is distinct from p_is_active then
        if staff_row.staff_revision <> p_expected_revision then
            raise exception 'La cuenta cambió. Actualiza la información antes de modificarla.'
                using errcode = '40001';
        end if;
        previous := jsonb_build_object(
            'full_name', staff_row.full_name, 'job_title', staff_row.job_title,
            'modules', to_jsonb(staff_row.allowed_modules), 'is_active', staff_row.is_active
        );
        update public.business_memberships
        set full_name = btrim(p_full_name),
            job_title = btrim(p_job_title),
            allowed_modules = normalized_modules,
            is_active = p_is_active,
            staff_revision = staff_revision + 1
        where user_id = p_user_id and billar_id = p_billar_id
        returning * into staff_row;

        insert into public.staff_account_audit (
            billar_id, actor_id, target_user_id, event_type, details
        ) values (
            p_billar_id, p_actor_id, p_user_id, 'update',
            jsonb_build_object(
                'before', previous,
                'after', jsonb_build_object(
                    'full_name', staff_row.full_name, 'job_title', staff_row.job_title,
                    'modules', to_jsonb(staff_row.allowed_modules), 'is_active', staff_row.is_active
                )
            )
        );
    end if;
    return jsonb_build_object(
        'user_id', staff_row.user_id, 'billar_id', staff_row.billar_id,
        'username', staff_row.username, 'full_name', staff_row.full_name,
        'job_title', staff_row.job_title, 'allowed_modules', to_jsonb(staff_row.allowed_modules),
        'is_active', staff_row.is_active, 'must_change_password', staff_row.must_change_password,
        'staff_revision', staff_row.staff_revision
    );
end;
$$;

