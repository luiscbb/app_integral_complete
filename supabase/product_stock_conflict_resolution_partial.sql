begin;

create table if not exists public.product_stock_reconciliation_audit (
    id bigint generated by default as identity primary key,
    billar_id text not null,
    product_id bigint not null,
    actor_id uuid not null,
    previous_stock double precision not null,
    resolved_stock double precision not null,
    previous_revision bigint not null,
    created_at timestamptz not null default now()
);

alter table public.product_stock_reconciliation_audit enable row level security;
revoke all on public.product_stock_reconciliation_audit from public, anon, authenticated;
grant select on public.product_stock_reconciliation_audit to authenticated;
drop policy if exists product_stock_reconciliation_audit_admin_select
    on public.product_stock_reconciliation_audit;
create policy product_stock_reconciliation_audit_admin_select
on public.product_stock_reconciliation_audit
for select to authenticated
using (public.has_billar_role(billar_id, array['admin']::text[]));

create or replace function public.resolve_product_stock_conflict(
    p_billar_id text,
    p_product_id bigint,
    p_expected_revision bigint,
    p_stock double precision
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    actor uuid := auth.uid();
    previous_stock double precision;
    previous_revision bigint;
    result_revision bigint;
begin
    if actor is null or p_billar_id is null or btrim(p_billar_id) = ''
       or p_product_id is null or p_expected_revision is null
       or (p_stock > '-Infinity'::double precision and
           p_stock < 'Infinity'::double precision) is not true then
        raise exception 'Datos de conciliación inválidos.' using errcode = '22023';
    end if;

    perform 1 from public.business_memberships membership
    where membership.user_id = actor and membership.billar_id = p_billar_id
      and membership.is_active and not membership.must_change_password
      and membership.role = 'admin'
    for share;
    if not found then
        raise exception 'Solo el administrador puede conciliar el inventario.'
            using errcode = '42501';
    end if;

    select stock, stock_revision into previous_stock, previous_revision
    from public.products
    where id = p_product_id and billar_id = p_billar_id
    for update;
    if not found then
        raise exception 'El producto no pertenece a este billar.' using errcode = '42501';
    end if;
    if previous_revision <> p_expected_revision then
        raise exception 'El inventario cambió en el servidor; vuelve a revisarlo.'
            using errcode = '40001';
    end if;

    update public.products
    set stock = p_stock, stock_revision = stock_revision + 1
    where id = p_product_id and billar_id = p_billar_id
    returning stock_revision into result_revision;

    insert into public.product_stock_reconciliation_audit (
        billar_id, product_id, actor_id, previous_stock, resolved_stock, previous_revision
    ) values (
        p_billar_id, p_product_id, actor, previous_stock, p_stock, previous_revision
    );
    return result_revision;
end;
$$;

revoke all on function public.resolve_product_stock_conflict(text, bigint, bigint, double precision)
    from public, anon;
grant execute on function public.resolve_product_stock_conflict(text, bigint, bigint, double precision)
    to authenticated;

commit;
